"""Assemble OUT/REPORT.md from the stages of scripts/bench.sh (`just bench`): every number with the hardware it was
measured on and the command that measured it, beside the figure the proposal (§B8) gives.

    python3 -I scripts/bench_report.py OUT

Standard library only. Reads what exists; a stage that did not run is reported as not run.
"""

import glob
import json
import os
import re
import sys

# The proposal's figures (§B8, draft 11) that the gas stage re-measures, by a substring of the scenario's log label
# (lower case). The proposal's vault row gives the figures before the security fixes of 11 November and adds
# "the fixes add 2.1k per deposit, 28.0k per checkpoint, 0 per release".
PROPOSAL_GAS = [
    ("release eth, real release seal", "release 373,657 (ETH)"),
    ("release erc20, real release seal", "release 403,523 (ERC-20)"),
    ("depositeth, first deposit of the tree", "deposit 159,285-198,427, plus 2.1k with the fixes"),
    ("depositeth, later deposit by the address", "deposit 159,285-198,427, plus 2.1k with the fixes"),
    ("deposit erc-20, second deposit", "deposit 159,285-198,427, plus 2.1k with the fixes"),
    ("submitcandidate, real checkpoint seal", "checkpoint under (A) 974,346 (+28.0k with the fixes): submit + recordBeacon + finalize"),
    ("finalize, real checkpoint seal", "checkpoint under (A), as above"),
    ("rule (b)", "checkpoint under (B) 542,969 is with the real verifier; this row uses the mock verifier"),
]


def read(p):
    try:
        return open(p, errors="replace").read()
    except OSError:
        return None


def gnu_time(text):
    out = {}
    for k, pat in (("wall", r"Elapsed \(wall clock\) time \(h:mm:ss or m:ss\): (\S+)"),
                   ("max_rss_kib", r"Maximum resident set size \(kbytes\): (\d+)"),
                   ("cpu", r"Percent of CPU this job got: (\S+)")):
        m = re.search(pat, text or "")
        if m:
            out[k] = m.group(1)
    return out


def last_json(text):
    for line in reversed((text or "").splitlines()):
        line = line.strip()
        if line.startswith("{"):
            try:
                return json.loads(line)
            except ValueError:
                continue
    return None


def gas_rows(log):
    rows, test = [], None
    for line in (log or "").splitlines():
        m = re.match(r"\[PASS\] (test\w+)\(\) \(gas: (\d+)\)", line.strip())
        if m:
            test = m.group(1)
            continue
        m = re.match(r"^\s{2}(.+?)\s+(\d+)$", line)
        if m and test:
            rows.append((test, m.group(1), int(m.group(2))))
    return rows


def scrub(out):
    """Name paths relative to the repository and the home directory as ~, so that no machine path is committed."""
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    spike = os.path.dirname(root)
    home = os.path.expanduser("~")
    for p in glob.glob(os.path.join(out, "**", "*"), recursive=True):
        if not os.path.isfile(p) or os.path.islink(p) or os.path.getsize(p) > 20 << 20:
            continue
        try:
            t = open(p, encoding="utf-8").read()
        except (UnicodeDecodeError, OSError):
            continue
        u = t.replace(root + "/", "./").replace(root, ".").replace(spike + "/", "<spike>/").replace(home, "~")
        if u != t:
            open(p, "w", encoding="utf-8").write(u)


def main(out):
    scrub(out)
    md = ["# Bench report", ""]
    hw = read(os.path.join(out, "hardware.json"))
    md += ["Generated by `just bench` (scripts/bench.sh, scripts/bench_report.py). Every figure below was measured in "
           "this run unless it is marked as the proposal's.", ""]
    md += ["## Hardware", ""]
    if hw:
        h = json.loads(hw)
        md += [f"- Where: {h.get('where')}; measured {h.get('measured_utc')}",
               f"- CPU: {', '.join(h.get('cpu_models') or ['unknown'])} ({', '.join(h.get('cpu_ids') or [])}); logical CPUs visible {h.get('logical_cpus_visible')}, "
               f"nproc {h.get('nproc')}, affinity {h.get('sched_affinity')}; flags {', '.join(h.get('flags_of_interest') or [])}",
               f"- cgroup CPU limit: {h.get('cgroup_cpu_max') or h.get('cgroup_cfs_quota_us')}; memory limit: "
               f"{h.get('cgroup_memory_max')}; {h.get('meminfo', {}).get('MemTotal')}",
               f"- Kernel {h.get('kernel')} ({h.get('machine')}); Modal: {json.dumps(h.get('modal'))}",
               f"- Toolchains: {json.dumps(h.get('toolchains'))}", ""]
    else:
        md += ["Not recorded (stage `hw` did not run).", ""]

    md += ["## Real proof: the release program's succinct receipt (CPU)", ""]
    d = os.path.join(out, "release-proof")
    prove = read(os.path.join(d, "prove.log"))
    if prove:
        t, rec = gnu_time(prove), last_json(prove)
        ex = last_json(read(os.path.join(d, "exec.log")))
        ver = read(os.path.join(d, "verify.log"))
        idj = last_json(read(os.path.join(d, "image-id.json")))
        md += ["| What | Measured | The proposal (§B8, P.4) |", "|---|---|---|",
               f"| image id | `{(idj or {}).get('image_id')}` | release `0x17257f91…f5cd` (crown run) |",
               f"| user cycles (executor) | {(ex or {}).get('user_cycles', 'see exec.log')} | 77,736 |",
               f"| proving, wall (GNU time) | {t.get('wall')} at {t.get('cpu')} CPU | 46 s at 8 CPUs, 26.4-27.0 s at 16 |",
               f"| peak resident memory | {int(t.get('max_rss_kib', 0)) / 2**20:.2f} GiB | 1.5 GiB |",
               f"| receipt verified | {'yes' if ver is not None and 'error' not in ver.lower() else 'see verify.log'} | yes |",
               f"| prover's record | `{json.dumps(rec)[:300] if rec else 'none'}` | |", ""]
    else:
        md += ["Not run.", ""]

    md += ["## Ethereum gas (Foundry's schedule, `forge test --isolate`)", ""]
    rows = gas_rows(read(os.path.join(out, "gas", "gas-scenarios.log")))
    if rows:
        md += ["| Test | Scenario | Gas | The proposal (§B8) |", "|---|---|---:|---|"]
        for test, label, g in rows:
            ref = next((v for k, v in PROPOSAL_GAS if k in label.lower()), "")
            md.append(f"| `{test}` | {label} | {g:,} | {ref} |")
        real = {k: g for t, k, g in rows if t == "test_gas_everyStepWithTheRealVerifier"}
        parts = [real.get(k) for k in ("submitCandidate, real checkpoint seal (records a beacon)", "recordBeacon",
                                         "finalize, real checkpoint seal echoing the beacon")]
        if all(parts):
            md += ["", f"Derived: a checkpoint under (A) with the real verifier, submit + recordBeacon + finalize = "
                       f"{sum(parts):,} gas (the proposal: 974,346 before the fixes, plus 28.0k with them = 1,002,346)."]
        md.append("")
    else:
        md += ["Not run.", ""]

    md += ["## Light-client cycles (zkVM executor)", ""]
    head = read(os.path.join(out, "cycles", "headline.md"))
    md += [head.strip() if head and head.strip() else "Not run.", ""]

    md += ["## User-side proofs at the declared minimum (Modal containers held to the CPUs and memory below)", ""]
    runs = sorted(glob.glob(os.path.join(out, "user", "**", "run.json"), recursive=True))
    if runs:
        md += ["| Job | Run | Proofs (execute_and_prove, s) | Wall (s) | Peak RSS (GiB) | Settled |", "|---|---|---|---:|---:|---|"]
        for r in runs:
            j = json.load(open(r))
            job = os.path.basename(os.path.dirname(os.path.dirname(r)))
            pr = ", ".join(f"{p.get('label')}: {p.get('execute_and_prove_s')}" for p in j.get("proofs") or [])
            rss = int((j.get("gnu_time") or {}).get("max_rss_kib", 0)) / 2**20
            md.append(f"| {job} | {j.get('run')} | {pr} | {j.get('wall_s')} | {rss:.2f} | exit {j.get('settle_exit')} |")
        cont = sorted(glob.glob(os.path.join(out, "user", "**", "container.json"), recursive=True))
        if cont:
            c = json.load(open(cont[0]))
            md += ["", f"Container: {json.dumps(c.get('declared'))}, nproc {c.get('nproc')}, "
                       f"{', '.join(c.get('cpuinfo_model_names') or [])}, {c.get('os')}, r0vm {c.get('r0vm_version')}"]
        md.append("")
    else:
        md += ["Not run (`just bench-user`).", ""]
    open(os.path.join(out, "REPORT.md"), "w").write("\n".join(md) + "\n")
    print(f"{out}/REPORT.md")


if __name__ == "__main__":
    main(sys.argv[1])
