HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SCRIPT = os.path.join(HERE, "release_manifest.py")


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


rm = load("release_manifest", SCRIPT)
fn = load("fetch_native", os.path.join(HERE, "fetch_native.py"))
cn = load("crate_notices", os.path.join(HERE, "crate_notices.py"))
REAL_PINS = fn.load_pins(fn.PINS)
SOURCES = {os.path.basename(s["url"]): f"{s['name']} test bytes\n".encode() for s in REAL_PINS["sources"]}


def sha(b):
    return hashlib.sha256(b).hexdigest()


def rd(p, mode="r"):
    with open(p, mode) as f:
        return f.read()


def wr(p, data):
    os.makedirs(os.path.dirname(p) or ".", exist_ok=True)
    with open(p, "wb" if isinstance(data, bytes) else "w") as f:
        f.write(data)


