# a small crate graph, its lockfile and cargo's answers (shared with scripts/test_release_scripts.py)
# ---------------------------------------------------------------------------------------------------------------
REG = "registry+https://github.com/rust-lang/crates.io-index"
APACHE = "Apache License\nVersion 2.0, January 2004\nhttp://www.apache.org/licenses/\n(test text)\n"


def crate_graph(base, own_manifest):
    """Write the packages' directories under base/registry; return (metadata, cargo tree text, Cargo.lock text).
    own_manifest: the Cargo.toml path of Ferrata's own crate (inside the crate_notices module's ROOT)."""
    reg = os.path.join(base, "registry")
    pk = []

    def package(name, version, licence, files, authors=(), links=None, lib=True):
        d = os.path.join(reg, f"{name}-{version}")
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, ".cargo-ok"), "w").close()
        for rel, text in files.items():
            wr(os.path.join(d, rel), text)
        pk.append({"id": f"{REG}#{name}@{version}", "name": name, "version": version, "source": REG,
                   "manifest_path": os.path.join(d, "Cargo.toml"), "license": licence, "license_file": None,
                   "authors": list(authors), "links": links,
                   "targets": [{"kind": ["lib"], "name": name.replace("-", "_")}] if lib else []})

    package("serde", "1.0.0", "MIT OR Apache-2.0",
            {"LICENSE-MIT": "Copyright (c) 2014 The Serde Authors\n\nPermission is hereby granted (test text)\n",
             "LICENSE-APACHE": APACHE})
    package("mitonly", "0.1.0", "MIT", {}, authors=["Ada Example <ada@example.invalid>"])
    package("native-sys", "0.2.0", "Apache-2.0 AND BSD-3-Clause",
            {"LICENSE": APACHE, "vendor/c/LICENSE": "Copyright (c) 2020 C Authors. BSD-3-Clause (test text)\n",
             "vendor/c/x.c": "/* Copyright 2020 C Authors\n * SPDX-License-Identifier: BSD-3-Clause */\nint x;\n"},
            links="native")
    own = {"id": f"path+file://{os.path.dirname(own_manifest)}#ferrata-cli@0.1.0", "name": "ferrata-cli",
           "version": "0.1.0", "source": None, "manifest_path": own_manifest, "license": "MIT OR Apache-2.0",
           "license_file": None, "authors": [], "links": None, "targets": [{"kind": ["bin"], "name": "ferrata"}]}
    meta = {"packages": [own] + pk, "workspace_members": [own["id"]], "version": 1}
    tree = "\n".join([f"ferrata-cli v0.1.0 ({os.path.dirname(own_manifest)})", "serde v1.0.0", "mitonly v0.1.0",
                      "native-sys v0.2.0", "serde v1.0.0 (*)"]) + "\n"
    lock = "version = 4\n\n[[package]]\nname = \"ferrata-cli\"\nversion = \"0.1.0\"\n" + "".join(
        f"\n[[package]]\nname = \"{p['name']}\"\nversion = \"{p['version']}\"\nsource = \"{REG}\"\n" for p in pk) + \
        "\n[[package]]\nname = \"notlinked\"\nversion = \"9.0.0\"\nsource = \"" + REG + "\"\n" + \
        "\n[[package]]\nname = \"object\"\nversion = \"0.39.1\"\nsource = \"" + REG + "\"\n"   # a build dependency's
    return meta, tree, lock


STD_HTML = ("<html><h1>Copyright notices for The Rust Standard Library</h1><h3>📦 gimli-0.32.3</h3>"
            '<p>URL: <a href="https://crates.io/crates/gimli/0.32.3">https://crates.io/crates/gimli/0.32.3</a></p></html>\n')
STD_RLIBS = {"libcore-0123456789abcdef.rlib": b"core", "liballoc-0123456789abcdef.rlib": b"alloc",
             "libstd-0123456789abcdef.rlib": b"std /rust/deps/object-0.37.3/src/read/mod.rs",
             "libobject-0123456789abcdef.rlib": b"/rust/deps/object-0.37.3/src/read/elf.rs",
             "libmemchr-0123456789abcdef.rlib": b"/rust/deps/memchr-2.7.6/src/lib.rs",
             "libgimli-0123456789abcdef.rlib": b"/rust/deps/gimli-0.32.3/src/read/mod.rs"}


def sysroot(base, rlibs=None):
    """A toolchain's sysroot as crate_notices.py reads it: COPYRIGHT-library.html and the target's rlibs."""
    d = os.path.join(base, "sysroot")
    wr(os.path.join(d, "share", "doc", "rust", "COPYRIGHT-library.html"), STD_HTML)
    for n, b in (rlibs or STD_RLIBS).items():
        wr(os.path.join(d, "lib", "rustlib", "x86_64-unknown-linux-gnu", "lib", n), b)
    return d


def crate_files(base, cli_dir, out, module=cn):
    """Generate crates.tsv, THIRD-PARTY-CRATES.md and the standard library's notices into out, for cli_dir/Cargo.lock
    (written here) and the crate graph above."""
    meta, tree, lock = crate_graph(base, os.path.join(module.ROOT, "cli", "Cargo.toml"))
    wr(os.path.join(cli_dir, "Cargo.lock"), lock)
    msgs = os.path.join(base, "crate-messages.jsonl")
    wr(msgs, "".join(json.dumps({"reason": "compiler-artifact", "package_id": p["id"],
                                 "target": {"kind": p["targets"][0]["kind"] if p["targets"] else ["lib"]}}) + "\n"
                     for p in meta["packages"]))
    with contextlib.redirect_stdout(io.StringIO()):
        module.generate(cli_dir, msgs, out, tree_text=tree, meta=meta, sysroot=sysroot(base),
                        rustc_version="rustc 0.0.0 (test)")
    return meta, tree, lock


class Release(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.out = self.tmp.name
        self.d = os.path.join(self.out, "ferrata-9.9.9")
        self.pins = os.path.join(self.out, "pins.json")
        p = json.loads(json.dumps(REAL_PINS))
        for s in p["sources"]:
            b = SOURCES[os.path.basename(s["url"])]
            s["bytes"], s["sha256"] = len(b), sha(b)
        wr(self.pins, json.dumps(p))
        self.layout(self.d)
        self.tar = self.sources_tar(os.path.join(self.out, "ferrata-9.9.9-third-party-sources.tar"))

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, rel, data):
        p = os.path.join(self.d, rel)
        wr(p, data if isinstance(data, bytes) else data.encode())
        return data if isinstance(data, bytes) else data.encode()

    def layout(self, d):
        ids, jsonl = [], []
        for i, f in enumerate(["ferrata_lez.bin", "ferrata_bridge.bin"]):
            b = self.write(f"programs/{f}", f"lez program {i}")
            ids.append(f"{f} {sha(b)} {'%02x' % (i + 1) * 32}")
        for i, f in enumerate(["checkpoint.bin", "checkpoint_b.bin", "segment.bin", "release.bin"]):
            b = self.write(f"programs/{f}", f"r0bf program {i}")
            jsonl.append(json.dumps({"program": f, "image_id": "0x" + "%02x" % (i + 3) * 32, "sha256": sha(b)}))
        self.write("programs/ids.txt", "\n".join(ids) + "\n")
        self.write("programs/ids.jsonl", "\n".join(jsonl) + "\n")
        art = {"bytecode": {"object": "0x6001600055", "linkReferences": {}}, "deployedBytecode": {"object": "0x600160"},
               "metadata": {"compiler": {"version": "0.8.26"}, "settings": {"evmVersion": "cancun", "optimizer": {"enabled": True}}}}
        for n in ("FerrataVault", "FerrataRegistry"):
            self.write(f"vault/{n}.json", json.dumps(art))
        cli = self.write("cli/ferrata", b"\x7fELF not really")
        line = "check-build: every build script linked native code only from ... (test)"
        rec = fn.build_record(REAL_PINS, {"compiling": ["aws-lc-sys"]}, line, "cli")
        rec["binary"] = {"name": "ferrata", "bytes": len(cli), "sha256": sha(cli)}
        self.write("cli/check-build.json", json.dumps(rec, indent=1))
        self.write("toolchains.txt", "lez 1806e873ea2ac0e1b608aa7cf2f9b6e1fb12db21\n"
                   + "\n".join(fn.record_lines(rec["archives"])) + "\n")
        for f in ("LICENSE-MIT", "LICENSE-APACHE"):
            shutil.copy(os.path.join(ROOT, f), os.path.join(d, f))
        shutil.copy(os.path.join(ROOT, "releases/third-party/THIRD-PARTY-NOTICES.md"), d)
        shutil.copytree(os.path.join(ROOT, "releases/third-party/licenses"), os.path.join(d, "licenses"))
        gen = os.path.join(self.out, "generated")
        crate_files(os.path.join(self.out, "crates"), os.path.join(d, "cli"), gen)
        shutil.copy(os.path.join(gen, cn.CRATES), os.path.join(d, "cli", cn.CRATES))
        shutil.copy(os.path.join(gen, cn.NOTICES), os.path.join(d, cn.NOTICES))
        shutil.copy(os.path.join(gen, cn.STD), os.path.join(d, "licenses", cn.STD))
        self.build_ok = os.path.join(self.out, "BUILD-OK")
        wr(self.build_ok, f"commit abc123\nfinished_utc 2026-11-22T00:00:00Z\nsteps guests vault cli\n"
                          f"cli_sha256 {sha(cli)}\ncheck_build_sha256 {sha(rd(os.path.join(d, 'cli/check-build.json'), 'rb'))}\n"
                          f"crate_notices_sha256 {sha(rd(os.path.join(d, cn.NOTICES), 'rb'))}\n")

    def sources_tar(self, path, names=None, content=None):
        with tarfile.open(path, "w") as t:
            for n in names or sorted(SOURCES):
                b = content if content is not None else SOURCES[n]
                ti = tarfile.TarInfo(f"ferrata-9.9.9-third-party-sources/{n}")
                ti.size = len(b)
                t.addfile(ti, io.BytesIO(b))
        return path

    def make(self, tar=None, build_ok=None):
        return subprocess.run([sys.executable, "-I", SCRIPT, "make", self.d, "9.9.9", "abc123", tar or self.tar,
                               build_ok if build_ok is not None else self.build_ok, "--pins", self.pins],
                              capture_output=True, text=True)

    def check(self, *extra):
        return subprocess.run([sys.executable, "-I", SCRIPT, "check", self.d, *extra], capture_output=True, text=True)

    def rewrite_manifest_entry(self, key, rel):
        """What someone hiding a change would do: the manifest's entry rewritten to the file's new size and sha256."""
        p = os.path.join(self.d, "MANIFEST.json")
        m = json.loads(rd(p))
        b = rd(os.path.join(self.d, rel), "rb")
        e = m[key] if key in m else m["third_party"][key]
        e["bytes"], e["sha256"] = len(b), sha(b)
        wr(p, json.dumps(m))

    def test_complete_release(self):
        r = self.make()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("2 native archives covered by THIRD-PARTY-NOTICES.md, the crates by THIRD-PARTY-CRATES.md", r.stdout)
        c = self.check("--strict")
        self.assertEqual(c.returncode, 0, c.stdout)
        self.assertIn("covers the 2 native archives and their 9 components", c.stdout)
        self.assertIn("cli/ferrata is the binary check-build passed", c.stdout)
        m = json.loads(rd(os.path.join(self.d, "MANIFEST.json")))
        self.assertEqual([a["sha256"] for a in m["native"]], [a["sha256"] for a in REAL_PINS["archives"]])
        self.assertEqual(m["third_party"]["sources"]["sha256"], sha(rd(self.tar, "rb")))
        self.assertEqual({x["file"]: x["sha256"] for x in m["third_party"]["sources"]["contents"]},
                         {n: sha(b) for n, b in SOURCES.items()})
        self.assertEqual(m["build"]["cli_sha256"], m["cli"]["sha256"])
        self.assertIn("do not depend on where the tree is", m["image_ids_note"])     # L3: the old note was false
        self.assertIn("1806e873ea2ac0e1b608aa7cf2f9b6e1fb12db21", m["targets"]["lez"])
        notices = rd(os.path.join(self.d, cn.NOTICES))
        self.assertIn("| mitonly | 0.1.0 | crates.io | MIT | MIT | T", notices)
        self.assertIn("Copyright (c) Ada Example", notices)                          # MIT with the package's authors
        self.assertIn("`BSD-3-Clause` (1)", notices)                                # the C source's SPDX identifier
        self.assertNotIn("notlinked", notices)                                       # in the lockfile, not linked

    def test_notices_removed_after_make(self):
        self.assertEqual(self.make().returncode, 0)
        os.unlink(os.path.join(self.d, "THIRD-PARTY-NOTICES.md"))
        c = self.check()
        self.assertEqual(c.returncode, 1)
        self.assertIn("THIRD-PARTY-NOTICES.md missing", c.stdout)

    def test_notices_without_an_archive(self):
        p = os.path.join(self.d, "THIRD-PARTY-NOTICES.md")
        wr(p, rd(p).replace(REAL_PINS["archives"][1]["sha256"], "0" * 64))
        r = self.make()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("does not name logos-blockchain-circuits-v0.5.7-linux-x86_64.tar.gz with its sha256", r.stderr)

    def test_licence_text_missing(self):
        os.unlink(os.path.join(self.d, "licenses", "GPL-2.0.txt"))
        r = self.make()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("licenses/GPL-2.0.txt missing", r.stderr)

    def test_toolchains_without_the_pinned_archive(self):
        p = os.path.join(self.d, "toolchains.txt")
        wr(p, rd(p).replace(REAL_PINS["archives"][0]["sha256"], "f" * 64))
        r = self.make()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("does not record rapidsnark 0.0.8 with the pinned sha256", r.stderr)

    def test_sources_tar_without_a_pinned_source(self):
        tar = self.sources_tar(os.path.join(self.out, "short.tar"), names=["gmp-6.3.0.tar.xz"])
        r = self.make(tar)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("lacks ['gmp-6.2.1.tar.xz']", r.stderr)

    def test_sources_tar_with_other_bytes(self):
        tar = self.sources_tar(os.path.join(self.out, "other.tar"), content=b"not GMP")
        r = self.make(tar)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("differ from the pinned sha256", r.stderr)

    def test_sources_asset_beside_the_release(self):
        self.assertEqual(self.make().returncode, 0)
        with open(self.tar, "ab") as f:
            f.write(b"\0" * 512)
        c = self.check()
        self.assertEqual(c.returncode, 1)
        self.assertIn("beside the release differs from the manifest", c.stdout)
        os.unlink(self.tar)
        self.assertEqual(self.check().returncode, 0)
        c = self.check("--strict")
        self.assertEqual(c.returncode, 1)
        self.assertIn("is not beside the release directory", c.stdout)

    def test_no_sources_tar(self):
        r = subprocess.run([sys.executable, "-I", SCRIPT, "make", self.d, "9.9.9", "abc123"], capture_output=True, text=True)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("sources tarball", r.stderr)

    def test_manifest_made_before_the_notices(self):
        self.assertEqual(self.make().returncode, 0)
        p = os.path.join(self.d, "MANIFEST.json")
        m = json.loads(rd(p))
        for k in ("native", "third_party", "licence", "build"):
            m.pop(k)
        wr(p, json.dumps(m))
        c = self.check()
        self.assertEqual(c.returncode, 1)
        self.assertIn("made before the third-party notices", c.stdout)
        self.assertIn("no BUILD-OK", c.stdout)

    def test_new_component_not_in_the_notices(self):
        # A native component added to scripts/native-deps.json without a line in the notices must be caught.
        pins = json.loads(json.dumps(REAL_PINS))
        pins["archives"][0]["components"].append({"name": "libsomething", "version": "1.0", "licence": "GPL-2.0-only",
                                                  "in": "lib/libsomething.a", "source": "x", "texts": ["GPL-2.0.txt"]})
        rec = json.loads(rd(os.path.join(self.d, "cli/check-build.json")))
        tool = {f"native_{a['name']}": f"{a['version']} sha256 {a['sha256']} {a['url']}" for a in pins["archives"]}
        probs = rm.notices_problems(self.d, {"native": rm.native_section(rec, tool, pins)})
        self.assertTrue(any("libsomething" in p for p in probs), probs)
        self.assertEqual(rm.notices_problems(self.d, {"native": rm.native_section(rec, tool, REAL_PINS)}), [])

    # --- review-fix-supply M-2: only the binary check-build passed, from a build whose every step passed ---
    def test_no_build_ok(self):
        r = self.make(build_ok=os.path.join(self.out, "absent"))
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("BUILD-OK is required", r.stderr)

    def test_cli_not_the_checked_binary(self):
        self.write("cli/ferrata", b"not the checked binary\n")       # the reviewer's case: another file in its place
        r = self.make()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("is not the binary check-build passed", r.stderr)
        self.assertIn("BUILD-OK's cli_sha256", r.stderr)

    def test_no_check_build_record(self):
        os.unlink(os.path.join(self.d, "cli/check-build.json"))
        r = self.make()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("cli/check-build.json missing", r.stderr)

    def test_failed_check_build_record(self):
        p = os.path.join(self.d, "cli/check-build.json")
        rec = json.loads(rd(p))
        rec["result"] = "fail"
        wr(p, json.dumps(rec))
        r = self.make()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("not pass", r.stderr)

    def test_cli_swapped_after_make(self):
        self.assertEqual(self.make().returncode, 0)
        self.write("cli/ferrata", b"\x7fELF another binary")
        self.rewrite_manifest_entry("cli", "cli/ferrata")
        c = self.check("--strict")
        self.assertEqual(c.returncode, 1)
        self.assertIn("is not the binary check-build passed", c.stdout)

    # --- review-fix-supply M-1: the crate notices match the dependency set and the lockfile ---
    def test_crate_missing_from_the_notices(self):
        p = os.path.join(self.d, cn.NOTICES)
        wr(p, "".join(l for l in rd(p).splitlines(keepends=True) if not l.startswith("| mitonly |")))
        r = self.make()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("does not list mitonly 0.1.0", r.stderr)

    def test_notices_for_another_lockfile(self):
        self.assertEqual(self.make().returncode, 0)
        p = os.path.join(self.d, "cli/Cargo.lock")
        wr(p, rd(p) + "\n[[package]]\nname = \"extra\"\nversion = \"1.0.0\"\nsource = \"" + REG + "\"\n")
        self.rewrite_manifest_entry("cli_lock", "cli/Cargo.lock")
        c = self.check()
        self.assertEqual(c.returncode, 1)
        self.assertIn("was made for another cli/Cargo.lock", c.stdout)

    def test_dependency_set_edited_after_make(self):
        self.assertEqual(self.make().returncode, 0)
        p = os.path.join(self.d, "cli", cn.CRATES)
        wr(p, "".join(l for l in rd(p).splitlines(keepends=True) if not l.startswith("native-sys\t")))
        self.rewrite_manifest_entry("cli_crates", "cli/" + cn.CRATES)
        c = self.check()
        self.assertEqual(c.returncode, 1)
        self.assertIn("made from another dependency set", c.stdout)


class CrateNotices(unittest.TestCase):
    """scripts/crate_notices.py on its own: licence choice, the set's cross-check with the build, the binary check."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.t = self.tmp.name

    def tearDown(self):
        self.tmp.cleanup()

    def test_used_under(self):
        self.assertEqual(cn.used_under("MIT OR Apache-2.0"), "Apache-2.0")
        self.assertEqual(cn.used_under("MIT/Apache-2.0"), "Apache-2.0")
        self.assertEqual(cn.used_under("MIT or Apache-2.0"), "Apache-2.0")
        self.assertEqual(cn.used_under("Unlicense OR MIT"), "MIT")
        self.assertEqual(cn.used_under("Apache-2.0 AND ISC"), "Apache-2.0 AND ISC")
        self.assertEqual(cn.used_under("(MIT OR Apache-2.0) AND Unicode-3.0"), "Apache-2.0 AND Unicode-3.0")
        self.assertEqual(cn.used_under("Apache-2.0 WITH LLVM-exception OR Apache-2.0 OR MIT"), "Apache-2.0")
        self.assertEqual(cn.used_under("ISC AND (Apache-2.0 OR ISC) AND Apache-2.0 AND MIT AND BSD-3-Clause AND "
                                       "(Apache-2.0 OR ISC OR MIT) AND (Apache-2.0 OR ISC OR MIT-0)"),
                         "Apache-2.0 AND BSD-3-Clause AND ISC AND MIT")
        self.assertIsNone(cn.used_under("MIT AND (Apache-2.0"))

    def test_a_package_the_build_did_not_compile(self):
        cli = os.path.join(self.t, "cli")
        meta, tree, lock = crate_graph(self.t, os.path.join(cn.ROOT, "cli", "Cargo.toml"))
        wr(os.path.join(cli, "Cargo.lock"), lock)
        msgs = os.path.join(self.t, "m.jsonl")
