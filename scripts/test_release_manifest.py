"""Tests of the release manifest's checks (review-code-ops M2; review-fix-supply M-1, M-2, L-7):
`python3 -I scripts/test_release_manifest.py`.

A synthetic release directory laid out as `scripts/release.sh package` lays one out, with the repository's own
THIRD-PARTY-NOTICES.md, licence texts and native archive pins, a check-build record and BUILD-OK as `release.sh build`
writes them, and crate notices generated by scripts/crate_notices.py from a small crate graph (a dual-licensed crate
with its files, an MIT crate without any, a crate compiling C with its own licence files, Ferrata's own crate):
`make` and `check` pass. Each of these fails: a missing or incomplete THIRD-PARTY-NOTICES.md, a missing licence text,
a toolchains.txt or check-build record that does not record the pinned archives, a sources tarball without a pinned
source or with other bytes under its name, a manifest made before the notices or before BUILD-OK, a native component
the notices do not list; no BUILD-OK, a CLI that is not the binary check-build passed (before `make`, and swapped
after it with the manifest rewritten to match), crate notices that do not match the dependency set, or that were made
for another lockfile; and, beside the release, a sources tarball that differs (absent: --strict fails). Standard
library only; files go to a temporary directory (TMPDIR).
"""

