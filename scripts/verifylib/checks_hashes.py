"""The hash family, offline: what the repository commits is re-hashed and compared with what it says elsewhere.

- `site-manifest-git`: the test network site's committed manifest against the git blobs it names (no network);
- `image-ids-agree`: the image ids of the deployed programs, the same in docs/image-ids.md, the reproduction list
  and the copy the site serves;
- `acc-leaf-vectors`: vectors/acc-leaf.json regenerated by an independent implementation (hashlib) of the
  accumulator-leaf facts, byte for byte.
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys

from .core import CheckFailed, Skipped, check, fail_if

MANIFEST = "deploy/testnet/web/trust/bridge/verify/manifest.json"


def _git(ctx):
    return getattr(ctx, "git_dir", None) or ctx.root


@check(id="site-manifest-git", family="hash", mode="offline", evidence=(239,),
       title="The test network site's committed manifest: every listed file equals the git blob it names",
       what=f"{MANIFEST}: each file's SHA-256 and size, and every file the repository does not hold",
       against="the blob at the commit and path the manifest names, read from this clone's git objects; for the "
               "files not from the repository, a SHA256SUMS committed under deploy/testnet/web/",
       needs=("python3", "git"), inputs=(MANIFEST,))
def site_manifest_git(ctx):
    m = json.loads((ctx.root / MANIFEST).read_text())
    files = m["files"]
    want = [f for f in files if f.get("commit") and f.get("repo_path")]
    cwd = _git(ctx)
    have = subprocess.run(["git", "cat-file", "--batch-check"], cwd=cwd, capture_output=True, text=True,
                          input="".join(f"{f['commit']}\n" for f in want)).stdout.splitlines()
    missing = sorted({ln.split()[0] for ln in have if ln.endswith(" missing")})
    if missing:
        raise Skipped(f"this clone lacks {len(missing)} commit(s) the manifest names ({missing[0][:12]}…): a shallow "
                      "clone? `git fetch --unshallow` and run again")
    p = subprocess.run(["git", "cat-file", "--batch"], cwd=cwd, capture_output=True,
                       input="".join(f"{f['commit']}:{f['repo_path']}\n" for f in want).encode())
    out = p.stdout
    pos = 0
    problems = []
    for f in want:
        nl = out.index(b"\n", pos)
        header = out[pos:nl].decode()
        pos = nl + 1
        if header.endswith(" missing"):
            problems.append(f"{f['path']}: {f['commit'][:12]}:{f['repo_path']} is not in this clone")
            continue
        size = int(header.split()[2])
        blob = out[pos:pos + size]
        pos += size + 1
        if hashlib.sha256(blob).hexdigest() != f["sha256"] or size != f.get("bytes", size):
            problems.append(f"{f['path']}: the manifest says sha256 {f['sha256'][:16]}… ({f.get('bytes')} B); the blob "
                            f"{f['commit'][:12]}:{f['repo_path']} hashes to {hashlib.sha256(blob).hexdigest()[:16]}… "
                            f"({size} B)")
    sums = {}
    for sf in (ctx.root / "deploy/testnet/web").rglob("SHA256SUMS"):
        for ln in sf.read_text().splitlines():
            parts = ln.split()
            if len(parts) >= 2 and re.fullmatch(r"[0-9a-f]{64}", parts[0]):
                sums.setdefault(parts[0], []).append(str(sf.relative_to(ctx.root)))
    other = [f for f in files if not (f.get("commit") and f.get("repo_path"))]
    for f in other:
        if f["sha256"] not in sums:
            problems.append(f"{f['path']}: not from the repository, and no committed SHA256SUMS lists its sha256")
    fail_if(problems, "the site's manifest against git")
    return [f"{len(want)} of {len(want)} files equal the git blob the manifest names (commits "
            f"{', '.join(sorted({f['commit'][:8] for f in want}))}); {len(other)} files not from the repository, "
            f"each listed in a committed SHA256SUMS; {len(m.get('generated', []))} generated on the host (listed, "
            "not hashed); manifest made " + str(m.get("made", "?"))]


def _image_rows(text: str) -> dict:
    """name -> (image id, binary sha256 or None) from docs/image-ids.md's tables (`name` | `0x…` | `sha…`)."""
    out = {}
    for ln in text.splitlines():
        if not ln.startswith("|"):
            continue
        ids = re.findall(r"0x[0-9a-f]{64}", ln)
        names = re.findall(r"`(ferrata_[a-z0-9_]+|checkpoint[a-z0-9_]*|release[a-z0-9_]*|segment[a-z0-9_]*)`", ln)
        shas = [h for h in re.findall(r"(?<![0-9a-fx])[0-9a-f]{64}(?![0-9a-f])", ln)]
        if ids and names:
            out.setdefault(names[-1], []).append((ids[0], shas[0] if shas else None))
    return out


@check(id="image-ids-agree", family="hash", mode="offline", evidence=(37, 82, 238),
       rows=("RFP-021 VS.3",),
       title="The deployed programs' image ids agree across the repository's records",
       what="each program of scripts/reproduce/deployed-programs.json: its image id and binary SHA-256",
       against="docs/image-ids.md (the reproducible build's ids) and the copy the site serves "
               "(deploy/testnet/web/trust/apps/registry.json)",
       inputs=("scripts/reproduce/deployed-programs.json", "docs/image-ids.md",
               "deploy/testnet/web/trust/apps/registry.json"))
def image_ids_agree(ctx):
    dep = json.loads((ctx.root / "scripts/reproduce/deployed-programs.json").read_text())
    doc = (ctx.root / "docs/image-ids.md").read_text()
    reg_path = ctx.root / "deploy/testnet/web/trust/apps/registry.json"
    problems = []
    if reg_path.exists() and json.loads(reg_path.read_text()) != dep:
        problems.append("deploy/testnet/web/trust/apps/registry.json is not scripts/reproduce/deployed-programs.json")
    for p in dep["programs"]:
        img = p["image_id"].lower()
        sha = p.get("binary_sha256", "").lower()
        rows = [ln for ln in doc.splitlines() if ln.startswith("|") and img in ln.lower()]
        names_md = (ctx.root / "names/image-ids.md")
        if not rows and names_md.exists():
            rows = [ln for ln in names_md.read_text().splitlines() if ln.startswith("|") and img in ln.lower()]
        if not rows:
            problems.append(f"{p['name']}: image id {img[:18]}… is in no table of docs/image-ids.md (or names/image-ids.md)")
        elif sha and not any(sha in ln.lower() for ln in rows):
            problems.append(f"{p['name']}: the row with its image id does not give its binary sha256 {sha[:16]}…")
    fail_if(problems, "the deployed programs' image ids")
    return [f"{len(dep['programs'])} of {len(dep['programs'])} deployed programs: image id and binary SHA-256 equal "
            "a row of the image-id tables; the site's copy of the list equal to the list"]


@check(id="acc-leaf-vectors", family="hash", mode="offline", evidence=(145,), rows=("RFP-021 F.6",),
       title="The accumulator-leaf vectors, regenerated independently (hashlib) and compared byte for byte",
       what="vectors/acc-leaf.json, which the Rust tests check ferrata-core's accumulator facts against",
       against="scripts/gen-acc-leaf-vectors.py's output, computed with hashlib alone, independent of the Rust code",
       inputs=("vectors/acc-leaf.json", "scripts/gen-acc-leaf-vectors.py"))
def acc_leaf_vectors(ctx):
    out = ctx.root / ".scratch" / "verify-acc-leaf.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    p = subprocess.run([sys.executable, "-I", "scripts/gen-acc-leaf-vectors.py", str(out)], cwd=ctx.root,
                       capture_output=True, text=True)
    if p.returncode != 0:
        raise CheckFailed(f"the generator failed: {p.stderr.strip()[-300:]}")
    got = out.read_bytes()
    want = (ctx.root / "vectors/acc-leaf.json").read_bytes()
    out.unlink()
    if got != want:
        raise CheckFailed(f"vectors/acc-leaf.json ({len(want)} B) differs from the regenerated vectors ({len(got)} B)")
    n = len(json.loads(want).get("cases", json.loads(want))) if want.strip().startswith(b"{") else "?"
    return [f"vectors/acc-leaf.json equal to its independent regeneration ({len(want)} bytes; {n} cases)"]
