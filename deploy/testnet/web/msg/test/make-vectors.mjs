// Writes test/vectors-v2.json: borsh of ferrata_msg_v2's messages, of each actor state (a profile, an inbox, an envelope
// holding one sealed message) and three PDAs, from this library, with fixed inputs. lez/msg-v2-wire/tests/vectors.rs
// decodes each with the program's own types and re-encodes it byte for byte (and derives the PDAs itself);
// test/msg.test.mjs decodes the states back and opens the message.
//   node deploy/testnet/web/msg/test/make-vectors.mjs
import { writeFileSync } from 'node:fs';
import * as M from '../ferrata-msg.js';

const A = new Uint8Array(32).fill(0x41), B = new Uint8Array(32).fill(0x42), P = new Uint8Array(32).fill(0xee);
const keysB = M.deriveKeys(new Uint8Array(32).fill(7), 0);
const recB = M.publicRecord(keysB);
let ctr = 0;
const rand = (n) => Uint8Array.from({ length: n }, () => (ctr++ * 37 + 11) & 0xff);
const text = 'Hello Bob: a fixed vector, hybrid X25519 + ML-KEM-768, ferrata_msg_v2.';
const NOW = 1790000000000n;
const body = M.seal({ sender: A, recipient: B, key: recB, text, sentMs: Number(NOW), rand });
const le = (v, n) => { let x = BigInt(v); return Uint8Array.from({ length: n }, () => { const b = Number(x & 0xffn); x >>= 8n; return b; }); };
const vec = (b) => M.concat(le(b.length, 4), b);
// Profile { key: Some(recB), policy: ContactsOnly, contacts: [A], blocked: [], sent_at: [NOW], last_send_ms: NOW, sent_total: 3 }
const profile = M.concat(
  Uint8Array.of(1), le(0, 4), recB.x25519, Uint8Array.of(1), vec(recB.mlkem768),
  Uint8Array.of(1), le(1, 4), A, le(0, 4), le(1, 4), le(NOW, 8), le(NOW, 8), le(3, 8),
);
// Inbox { owner: B, next_n: 2, entries: [Entry { n: 1, from: A, seq: 0, at_ms: NOW, len: body.len, contact: true }] }
const inbox = M.concat(B, le(2, 8), le(1, 4), le(1, 8), A, le(0, 8), le(NOW, 8), le(body.length, 4), Uint8Array.of(1));
// Envelope { recipient: B, from: A, seq: 0, at_ms: NOW, body }
const envelope = M.concat(B, A, le(0, 8), le(NOW, 8), vec(body));
const out = {
  note: 'generated by test/make-vectors.mjs; checked by test/msg.test.mjs and lez/msg-v2-wire/tests/vectors.rs',
  keys: { x25519: M.hex(recB.x25519), mlkem768: M.hex(recB.mlkem768) },
  messages: {
    publish: M.hex(M.encodePublish(recB)),
    set_policy_contacts_only: M.hex(M.encodeSetPolicy(M.POLICY.contactsOnly)),
    contacts_add_a_remove_b: M.hex(M.encodeContacts([A], [B])),
    block_b: M.hex(M.encodeBlock([B], [])),
    send: M.hex(M.encodeSend({ to: B, nowMs: NOW, seq: 5n, body: Uint8Array.from([3, 0, 0, 0, 0, 9]) })),
    delete_3_5: M.hex(M.encodeDelete([5n, 3n, 5n])),
    clear_9: M.hex(M.encodeClear(9n)),
  },
  states: { profile: M.hex(profile), inbox: M.hex(inbox), envelope: M.hex(envelope), text, body_len: body.length },
  pdas: {
    program: M.hex(P),
    inbox_b: M.hex(M.inboxAccount(P, B)),
    envelope_b_a_0: M.hex(M.envelopeAccount(P, B, A, 0n)),
    envelope_b_a_7: M.hex(M.envelopeAccount(P, B, A, 7n)),
  },
};
writeFileSync(new URL('./vectors-v2.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log('vectors-v2.json written; envelope', body.length, 'bytes');
