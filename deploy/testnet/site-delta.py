#!/usr/bin/env python3
"""What a site deploy changes on the test network's host, and a package that installs exactly that, all or nothing.

    python3 -I deploy/testnet/site-delta.py plan [--manifest URL|FILE] [--ref REF] [--parts build,wallet|all]
    python3 -I deploy/testnet/site-delta.py pack --out DIR [the same options]

`plan` reads the manifest the host publishes (/bridge/verify/manifest.json: every file it serves with its SHA-256 and
the repository path it came from; `scripts/site-manifest.py verify` holds it to the host) and compares it with the
repository at REF (default HEAD): every served file whose content REF changes, every file of the build page's bundle
(its build.json "files") and of the wallet (sw.js's list, and sw.js) that REF adds, and every served file REF no
longer has (listed, never deleted). `--parts` picks what is deployed: build (the build page's bundle, at /), wallet
(/wallet/), msg, names, other (the explorer bundle and the host's pages), or all; changes outside it are listed as
left out. Read-only: one GET of the manifest (or a file), then git.

`pack` writes DIR/site-REF12.tar holding www/PATH for each file to install, SHA256SUMS (those files), EXPECT (the
SHA-256 each target has on the host now, as the manifest says, or "absent") and install.sh. On the host, as root,
`bash install.sh` checks the package and every target first and installs nothing if one differs from EXPECT (the host
moved since the manifest was made); otherwise it copies each old file to a backup directory and stages each new one
beside its target (root:root 644), removing what it staged and changing nothing if any of that fails, then renames
each staged file over its target (one rename per file: a reader sees the old file or the new one, never part of one). The wallet's config.json and the other files the host
generates are never in a package (the manifest lists them apart). Standard library only.
"""
import argparse
import hashlib
import io
import json
import re
import subprocess
import sys
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
NETWORK_DOC = "scripts/reproduce/deployed-programs.json"
SERVED_MANIFEST = "/bridge/verify/manifest.json"
BUILD = "deploy/testnet/web/build"
WALLET = "deploy/testnet/web/wallet"
PARTS = ("build", "wallet", "msg", "names", "other")
PATH_OK = re.compile(r"^[A-Za-z0-9._@+-][A-Za-z0-9._@+/-]*$")   # a web-root path install.sh can read unquoted

INSTALL_SH = r"""#!/usr/bin/env bash
# Generated by deploy/testnet/site-delta.py pack, REF {ref}: {n} file(s) under the web root, all or none. As root on
# the host: bash install.sh. WWW (default /srv/ferrata/www), OWNER (default root:root) and BACKUP may be set.
set -euo pipefail
HERE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
WWW="${{WWW:-/srv/ferrata/www}}"; OWNER="${{OWNER:-root:root}}"
BACKUP="${{BACKUP:-/var/lib/ferrata/site-backup/{ref12}-$(date -u +%Y%m%dT%H%M%SZ)}}"
cd "$HERE"
sha256sum -c --quiet SHA256SUMS || {{ echo "the package is not whole: nothing installed"; exit 1; }}
bad=0
while read -r want path; do
  if [ "$want" = absent ]; then
    [ ! -e "$WWW/$path" ] || {{ echo "present, the manifest says absent: $path"; bad=1; }}
  else
    got="$(sha256sum "$WWW/$path" 2>/dev/null | cut -d' ' -f1 || true)"
    [ "$got" = "$want" ] || {{ echo "not what the manifest says (${{got:-missing}}): $path"; bad=1; }}
  fi
done < EXPECT
[ "$bad" = 0 ] || {{ echo "the host differs from the manifest: nothing installed"; exit 1; }}
# Every old file kept and every new one staged beside its target before any target changes; a failure here removes
# what was staged and changes nothing. Then one rename per file.
mkdir -p "$BACKUP"
staged=()
unstage() {{ for s in "${{staged[@]}}"; do rm -f "$s"; done; echo "staging failed: nothing installed"; exit 1; }}
while read -r want path; do
  [ "$want" = absent ] || install -D -m 644 "$WWW/$path" "$BACKUP/$path" || unstage
  install -D -o "${{OWNER%%:*}}" -g "${{OWNER##*:}}" -m 644 "www/$path" "$WWW/$path.site-delta-new" || unstage
  staged+=("$WWW/$path.site-delta-new")
done < EXPECT
while read -r want path; do
  mv -f "$WWW/$path.site-delta-new" "$WWW/$path"
done < EXPECT
echo "installed $(wc -l < EXPECT) file(s) from {ref12}; the replaced ones are in $BACKUP"
"""


def git(*args, inp=None) -> bytes:
    return subprocess.run(["git", "-C", str(ROOT), *args], input=inp, capture_output=True, check=True).stdout


def blobs(ref: str, paths) -> dict:
    """{path: bytes} for each path that exists at ref (one `git cat-file --batch`)."""
    paths = list(dict.fromkeys(paths))
    if not paths:
        return {}
    out, got = git("cat-file", "--batch", inp="".join(f"{ref}:{p}\n" for p in paths).encode()), {}
    pos = 0
    for p in paths:
        nl = out.index(b"\n", pos)
        head = out[pos:nl].decode()
        pos = nl + 1
        if head.endswith(" missing"):
            continue
        size = int(head.split()[2])
        got[p] = out[pos:pos + size]
        pos += size + 1
    return got


def load_manifest(where: str) -> dict:
    if re.match(r"^https?://", where):
        req = urllib.request.Request(where, headers={"User-Agent": "ferrata-site-delta/1"})
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.loads(r.read())
    return json.loads(Path(where).read_text())


def part_of(path: str, build_files: set) -> str:
    if path.lstrip("/") in build_files:
        return "build"
    for prefix, part in (("/wallet/", "wallet"), ("/msg/", "msg"), ("/names/", "names")):
        if path.startswith(prefix):
            return part
    return "other"


def sw_files(sw_js: str) -> list:
    """The wallet's served files as its service worker lists them (between `const FILES = {` and `};`)."""
    m = re.search(r"const FILES = \{(.*?)\};", sw_js, re.S)
    if not m:
        raise SystemExit("site-delta: the wallet's sw.js has no FILES list")
    return re.findall(r"'([^']+)':\s*'[0-9a-f]{64}'", m.group(1))


def plan(manifest: dict, ref: str, parts) -> dict:
    """{"install": [(path, old sha or None, new bytes, part)], "left_out": [...], "gone": [...]} for ref."""
    head = blobs(ref, [f"{BUILD}/build.json", f"{WALLET}/sw.js"])
    if f"{BUILD}/build.json" not in head:
        raise SystemExit(f"site-delta: {BUILD}/build.json is not at {ref}")
    build_files = set(json.loads(head[f"{BUILD}/build.json"])["files"])
    entries = manifest.get("files") or []
    served = {e["path"]: e for e in entries}
    want = {}   # served path -> repository path, for every file this ref would serve from the parts it knows
    for e in entries:
        want[e["path"]] = e["repo_path"]
    for f in build_files:
        want.setdefault("/" + f, f"{BUILD}/{f}")
    if f"{WALLET}/sw.js" in head:
        for f in sw_files(head[f"{WALLET}/sw.js"].decode()) + ["sw.js"]:
            want.setdefault("/wallet/" + f, f"{WALLET}/{f}")
    files = blobs(ref, want.values())
    out = {"install": [], "left_out": [], "gone": []}
    for path in sorted(want):
        repo_path, entry = want[path], served.get(path)
        if repo_path not in files:
            if entry:
                out["gone"].append((path, repo_path))
            continue
        data = files[repo_path]
        if entry and hashlib.sha256(data).hexdigest() == entry["sha256"]:
            continue
        if not PATH_OK.match(path.lstrip("/")) or ".." in path.split("/"):
            raise SystemExit(f"site-delta: an unexpected path: {path!r}")
        item = (path, entry["sha256"] if entry else None, data, part_of(path, build_files), repo_path)
        out["install" if item[3] in parts else "left_out"].append(item)
    return out


def show(p: dict, ref: str, manifest: dict) -> None:
    print(f"site-delta: the host's manifest (made {manifest.get('made', '?')}) against {ref}")
    for title, items in (("install", p["install"]), ("changed but outside --parts (not installed)", p["left_out"])):
        print(f"{title}: {len(items)}")
        for path, old, data, part, repo_path in items:
            print(f"  {part:6} {path}  {'new' if old is None else old[:12] + ' -> ' + hashlib.sha256(data).hexdigest()[:12]}  ({repo_path})")
    if p["gone"]:
        print(f"served but not at {ref} (left on the host): {len(p['gone'])}")
        for path, repo_path in p["gone"]:
            print(f"  {path}  ({repo_path})")


def pack(p: dict, ref_commit: str, out_dir: Path) -> Path:
    if not p["install"]:
        raise SystemExit("site-delta: nothing to install")
    out_dir.mkdir(parents=True, exist_ok=True)
    tar_path = out_dir / f"site-{ref_commit[:12]}.tar"
    sums, expect = [], []
    with tarfile.open(tar_path, "w") as tar:
        def add(name, data, mode=0o644):
            info = tarfile.TarInfo(name)
            info.size, info.mode, info.mtime, info.uname, info.gname = len(data), mode, 0, "root", "root"
            tar.addfile(info, io.BytesIO(data))
        for path, old, data, _part, _repo in p["install"]:
            rel = path.lstrip("/")
            add(f"www/{rel}", data)
            sums.append(f"{hashlib.sha256(data).hexdigest()}  www/{rel}")
            expect.append(f"{old or 'absent'} {rel}")
        add("SHA256SUMS", ("\n".join(sums) + "\n").encode())
        add("EXPECT", ("\n".join(expect) + "\n").encode())
        add("install.sh", INSTALL_SH.format(ref=ref_commit, ref12=ref_commit[:12], n=len(expect)).encode(), 0o755)
    return tar_path


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("command", choices=("plan", "pack"))
    ap.add_argument("--manifest", help="the host's manifest: a URL or a file (default: the test network's, "
                                       f"{NETWORK_DOC}'s network + {SERVED_MANIFEST})")
    ap.add_argument("--ref", default="HEAD")
    ap.add_argument("--parts", default="build,wallet", help=f"comma-separated, of {', '.join(PARTS)}; or all")
    ap.add_argument("--out", help="pack: the directory the package is written to")
    a = ap.parse_args(argv)
    parts = set(PARTS) if a.parts == "all" else set(a.parts.split(","))
    if parts - set(PARTS):
        ap.error(f"--parts: unknown {sorted(parts - set(PARTS))}")
    where = a.manifest or json.loads((ROOT / NETWORK_DOC).read_text())["network"].rstrip("/") + SERVED_MANIFEST
    manifest = load_manifest(where)
    commit = git("rev-parse", "--verify", a.ref + "^{commit}").decode().strip()
    p = plan(manifest, commit, parts)
    show(p, f"{a.ref} ({commit[:12]})", manifest)
    if a.command == "pack":
        if not a.out:
            ap.error("pack needs --out DIR")
        t = pack(p, commit, Path(a.out))
        print(f"wrote {t} ({t.stat().st_size} bytes), sha256 {hashlib.sha256(t.read_bytes()).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
