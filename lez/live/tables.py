#!/usr/bin/env python3
"""Tables of a recorded run, from its manifest (results/run.tsv) and its per-block table
(results/chain.tsv): written to results/tables.md. Standard library only.

    python3 lez/live/tables.py [results directory]

Every figure is copied or summed from those two files; nothing is measured here.
"""

import csv
import os
import sys


def read_tsv(path):
    with open(path, newline="") as f:
        return [{k: ("" if v == "-" else v) for k, v in row.items()} for row in csv.DictReader(f, delimiter="\t")]


def n(value):
    return f"{int(value):,}" if value not in ("", None) else "–"


def result(row):
    if row["status"] == "refused":
        return f"refused: exit {row['exit']}"
    if row["status"] == "reverted":
        return "reverted: " + row["note"].split(";")[0]
    return row["status"]


def delta(live, harness):
    if live == "" or harness == "":
        return "–"
    d = int(live) - int(harness)
    return "=" if d == 0 else f"{d:+,}"


def table(rows, with_harness=True):
    if with_harness:
        out = [
            "| # | transaction | block | result | execution gas | harness | storage gas (tx bytes) | harness | base fee |",
            "|---|---|---:|---|---:|---:|---:|---:|---:|",
        ]
        for i, r in enumerate(rows, 1):
            out.append(
                f"| {i} | {r['step']} | {r['block'] or '–'} | {result(r)} | {n(r['exec_gas'])} | "
                f"{delta(r['exec_gas'], r['harness_exec_gas'])} | {n(r['stor_gas'])} | "
                f"{delta(r['stor_gas'], r['harness_stor_gas'])} | {n(r['fee'])} |"
            )
    else:
        out = [
            "| # | transaction | block | result | execution gas | storage gas (tx bytes) | base fee |",
            "|---|---|---:|---|---:|---:|---:|",
        ]
        for i, r in enumerate(rows, 1):
            out.append(
                f"| {i} | {r['step']} | {r['block'] or '–'} | {result(r)} | {n(r['exec_gas'])} | {n(r['stor_gas'])} | {n(r['fee'])} |"
            )
    return "\n".join(out) + "\n"


def total(rows, column):
    return sum(int(r[column]) for r in rows if r[column] != "")


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    directory = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "results")
    rows = read_tsv(os.path.join(directory, "run.tsv"))
    chain = read_tsv(os.path.join(directory, "chain.tsv"))
    phase = lambda name: [r for r in rows if r["phase"] == name]
    out = ["# Tables of the recorded run\n", "Generated by `python3 lez/live/tables.py` from `run.tsv` and `chain.tsv`. "
           "\"harness\" columns: the difference to the same transaction in `lez/results/stage1-*.md` "
           "(`=`: equal; `–`: the harness has no such row).\n"]

    deploy = phase("deploy")
    out.append("## Deployment through LEZ's program loader\n")
    out.append(table(deploy, with_harness=False))
    names = []
    for r in deploy:
        name = r["step"].split(":")[0].replace("deploy ", "")
        if name not in names:
            names.append(name)
    for name in names:
        mine = [r for r in deploy if r["step"].startswith(f"deploy {name}:")]
        out.append(
            f"- `{name}`: {len(mine)} transactions in blocks {mine[0]['block']}–{mine[-1]['block']}, "
            f"execution gas {n(str(total(mine, 'exec_gas')))}, storage gas {n(str(total(mine, 'stor_gas')))}, "
            f"base fees {n(str(total(mine, 'fee')))}"
        )
    out.append("")

    replay = phase("replay")
    out.append("## `Init` and the five mainnet updates (instance A, main deployment)\n")
    out.append(table(replay))
    scenarios = phase("scenarios")
    out.append("## The finality path and the refusals (twin deployment)\n")
    out.append(table(scenarios))
    capacity = phase("capacity")
    if capacity:
        out.append("## Three transactions at once\n")
        out.append(table(capacity))
    private = phase("private")
    if private:
        out.append("## The private path\n")
        out.append("| transaction | block | result | execution gas | storage gas | base fee | the sequencer's words, or a note |")
        out.append("|---|---:|---|---:|---:|---:|---|")
        for r in private:
            out.append(
                f"| {r['step']} | {r['block'] or '–'} | {result(r)} | {n(r['exec_gas'])} | {n(r['stor_gas'])} | {n(r['fee'])} | {r['note']} |"
            )
        out.append("")

    out.append("## Totals\n")
    by_status = {}
    for r in rows:
        by_status[r["status"]] = by_status.get(r["status"], 0) + 1
    out.append(f"- transactions sent: {len(rows)} ({', '.join(f'{v} {k}' for k, v in sorted(by_status.items()))})")
    included = [r for r in rows if r["block"] != ""]
    out.append(
        f"- included: {len(included)}, in blocks {min(int(r['block']) for r in included)}–{max(int(r['block']) for r in included)}; "
        f"execution gas {n(str(total(included, 'exec_gas')))}, storage gas {n(str(total(included, 'stor_gas')))}, "
        f"base fees {n(str(total(included, 'fee')))}"
    )
    compared = [r for r in included if r["harness_exec_gas"] != ""]
    equal = [r for r in compared if r["harness_exec_gas"] == r["exec_gas"]]
    out.append(
        f"- with a harness row: {len(compared)}; execution gas equal to the harness's in {len(equal)}, different in {len(compared) - len(equal)}"
    )
    for r in compared:
        if r["harness_exec_gas"] != r["exec_gas"]:
            out.append(f"  - {r['step']}: {n(r['exec_gas'])} here, {n(r['harness_exec_gas'])} in the harness")
    stor = {}
    for r in compared:
        d = int(r["stor_gas"]) - int(r["harness_stor_gas"])
        stor[d] = stor.get(d, 0) + 1
    out.append("- storage gas (transaction bytes) against the harness: " + ", ".join(f"{d:+,} bytes in {c}" for d, c in sorted(stor.items())))
    debits = [(r, int(r["payer_debit"])) for r in included if r["payer_debit"] != "" and r["phase"] != "deploy"]
    agree = sum(1 for r, d in debits if d == int(r["fee"]))
    out.append(f"- the payer's balance on the sequencer fell by exactly the base fee in {agree} of {len(debits)} transactions where it was read before and after")
    alone = [r for r in included if r["block_txs"] == "1"]
    out.append(
        f"- alone in their block: {len(alone)} of {len(included)}; for these the sequencer's own totals in the block's fee transaction are the transaction's"
    )
    fees = [int(b["base_fee_exec"]) for b in chain]
    empty = sum(1 for b in chain if b["user_transactions"] == "0")
    finalized = sum(1 for b in chain if b["bedrock_status"] == "Finalized")
    over = [b for b in chain if int(b["gas_exec"]) > 5_000_000]
    out.append(
        f"- blocks: {len(chain)} ({empty} without a user transaction); execution base fee {min(fees)}–{max(fees)}; "
        f"blocks over the 5M execution target: {', '.join(b['block'] + ' (' + n(b['gas_exec']) + ')' for b in over) or 'none'}; "
        f"Finalized on Bedrock when the record was written: {finalized}"
    )
    if len(chain) > 2:
        spans = [int(chain[i]["timestamp_ms"]) - int(chain[i - 1]["timestamp_ms"]) for i in range(2, len(chain))]
        out.append(f"- block interval (timestamps of blocks 2–{len(chain)}): {min(spans) / 1000:.1f}–{max(spans) / 1000:.1f} s, mean {sum(spans) / len(spans) / 1000:.2f} s")
    out.append("")
    with open(os.path.join(directory, "tables.md"), "w") as f:
        f.write("\n".join(out))
    print("wrote", os.path.join(os.path.relpath(directory), "tables.md"))


if __name__ == "__main__":
    main()
