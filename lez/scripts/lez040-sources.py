#!/usr/bin/env python3
"""Write (or check) the LEZ v0.4.0 versions of the guest sources whose LEZ API changed in v0.4.0.

    python3 -I lez/scripts/lez040-sources.py          # write the *_lez040.rs files
    python3 -I lez/scripts/lez040-sources.py --check  # exit 1 if a file is missing or differs (CI job `links`)

LEZ v0.4.0 (LEZ #1144, authority only by explicit grants) made `ReceiveInput.is_authorized` a method over the grants
a delivery carries and gave `SyncMessage` the grants its sender attaches. A guest that reads the flag does not compile
on v0.4.0. The release candidates' source files are left exactly as they are, because any change to them, even one that
should compile to the same code, can change their builds and so the recorded image ids (measured: same-line edits
through inlined helpers changed 5 of 15). So each such file has a v0.4.0 twin, `<name>_lez040.rs`, generated here from
it by the substitutions below (each must match exactly as many times as listed), and lez/scripts/lez-select.sh points
the manifests' `path = ... # lez-select` lines at the twins on v0.4.0 only. Edit the original, then run this script.
"""
import sys
from pathlib import Path

LEZ = Path(__file__).resolve().parents[1]

HEADER = (
    "// GENERATED by lez/scripts/lez040-sources.py from {src} for LEZ v0.4.0 (lez/scripts/lez-select.sh v0.4.0): do not\n"
    "// edit; edit {src} and run the script. The release candidates build {src} itself.\n"
)

# The bridge's cosigners' chain: on the release candidates a signature authorized its actor on every delivery; on
# v0.4.0 only the transaction's root call holds the signers' grants, and a sync message carries only what its sender
# attaches, so each cosigner lends the next ones' grants along.
LEND_COSIGNERS = '''
// LEZ v0.4.0 (#1144): a sync message carries only the grants its sender attaches. The root call holds every cosigner's
// grant (each signs the transaction); each step of the cosigners' chain lends the remaining signers' grants along.
fn lend_cosigners(mut response: Response, input: &ReceiveInput, program: AccountId, signers: &[Root], at: usize) -> Response {
    let rest: Vec<_> = signers
        .iter()
        .skip(at + 1)
        .map(|s| own_actor(program, AccountId::new(*s)))
        .filter(|actor| input.grants.contains(actor))
        .collect();
    for message in &mut response.sync_messages {
        message.grants.extend(rest.iter().copied());
    }
    response
}
'''

SOURCES = [
    (
        "guests/bridge/src/main.rs",
        [
            ("if !input.is_authorized {", "if !input.is_authorized() {", 3),
            ("if input.from.is_some() || !input.is_authorized {", "if input.from.is_some() || !input.is_authorized() {", 1),
            ("if !input.is_authorized || input.from != previous {", "if !input.is_authorized() || input.from != previous {", 1),
            (
                "        return Ok(Response::keep_state()\n"
                "            .send_sync(next, &BridgeMessage::Cosigned { config_id, signers: signers.clone(), action }));\n",
                "        return Ok(lend_cosigners(\n"
                "            Response::keep_state()\n"
                "                .send_sync(next, &BridgeMessage::Cosigned { config_id, signers: signers.clone(), action }),\n"
                "            input,\n"
                "            program,\n"
                "            &signers,\n"
                "            at,\n"
                "        ));\n",
                1,
            ),
        ],
        LEND_COSIGNERS,
    ),
    ("guests/consumer/src/main.rs", [("if !input.is_authorized {", "if !input.is_authorized() {", 1)], ""),
    (
        "guests/msg/src/main.rs",
        [
            ("is_authorized: input.is_authorized,", "is_authorized: input.is_authorized(),", 1),
            (
                "SyncMessage { to, message, pda_seeds: Default::default() }",
                "SyncMessage { to, message, pda_seeds: Default::default(), grants: Default::default() }",
                1,
            ),
        ],
        "",
    ),
    (
        "guests/msg-v2/src/main.rs",
        [
            ("is_authorized: input.is_authorized,", "is_authorized: input.is_authorized(),", 1),
            (
                "SyncMessage { to, message: call.message, pda_seeds: Default::default() }",
                "SyncMessage { to, message: call.message, pda_seeds: Default::default(), grants: Default::default() }",
                1,
            ),
        ],
        "",
    ),
    ("names-wire/src/lib.rs", [("if !input.is_authorized {", "if !input.is_authorized() {", 1)], ""),
]


def twin_of(src: str) -> str:
    path = Path(src)
    return str(path.with_name(f"{path.stem}_lez040{path.suffix}"))


def generate(src: str, substitutions, append: str) -> str:
    text = (LEZ / src).read_text()
    for old, new, count in substitutions:
        found = text.count(old)
        if found != count:
            sys.exit(f"lez040-sources: {src}: {old!r} occurs {found} times, expected {count}")
        text = text.replace(old, new)
    return HEADER.format(src=Path(src).name) + text + append


def main() -> int:
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        sys.exit("usage: lez040-sources.py [--check]")
    stale = []
    for src, substitutions, append in SOURCES:
        want = generate(src, substitutions, append)
        twin = LEZ / twin_of(src)
        if check:
            if not twin.exists() or twin.read_text() != want:
                stale.append(twin_of(src))
        else:
            twin.write_text(want)
            print(f"lez040-sources: wrote lez/{twin_of(src)}")
    if stale:
        print(f"lez040-sources: stale (run lez/scripts/lez040-sources.py): {', '.join(stale)}", file=sys.stderr)
        return 1
    if check:
        print(f"lez040-sources: {len(SOURCES)} v0.4.0 twins up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
