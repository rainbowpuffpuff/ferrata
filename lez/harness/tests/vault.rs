//! Accumulator leaves through the program, and Ferrata's vault on Sepolia (`harness::vault`).

use harness::{render, vault};

const MAX_GAS_EXEC: u64 = 10_000_000;

/// The vault's request (its account, slots 0 and 1, deposit leaves against the root in slot 0)
/// through the program in the guest, on a synthetic state that holds the vault's own eight
/// deposits under a record in the Gloas layout; then the refusals.
#[test]
fn accumulator_leaves_through_the_program_on_a_synthetic_vault() {
    let (accepted, refused) = vault::synthetic_attestations();
    println!("{}", render(&accepted));
    println!("{}", render(&refused));
    for r in accepted.iter().chain(&refused) {
        assert!(r.charge.gas_exec <= MAX_GAS_EXEC, "{} is over MAX_GAS_EXEC", r.label);
    }
}

/// The same request on FerrataVault v5 on Sepolia (`e2e/runs/crown-live-1`), real state at a
/// finalized block: the instance follows the chain from the period-1378 bootstrap to the record
/// of finalized slot 11,556,608 (block 12,112,773), and the program attests slots 0 and 1 and each
/// deposit leaf; an address without an account; each deposit's event one EIP-2935 hop back (both
/// under the Gloas record); then the refusals. Writes `results/stage5-vault-v5.md`.
#[test]
fn the_vault_on_sepolia() {
    let (v, accepted, refused) = vault::real();
    let mut out = format!(
        "# FerrataVault v5 on Sepolia through the program: deposit leaves on real data\n\n\
         Generated by `RISC0_DEV_MODE=1 cargo test -p harness --locked --test vault` (see `../RESULTS.md`).\n\
         Fixture `crates/ferrata-spectests/fixtures/{}`: finalized slot {}, block {}, the vault \
         0x{} with root 0x{} over {} deposits.\n\n## Accepted\n\n",
        vault::VAULT_FIXTURE,
        v.slot,
        v.block,
        vault::VAULT_V5,
        hex::encode(v.root),
        v.count
    );
    out.push_str(&render(&accepted));
    out.push_str("\n## Refused\n\n");
    out.push_str(&render(&refused));
    println!("{out}");
    for r in accepted.iter().chain(&refused) {
        assert!(r.charge.gas_exec <= MAX_GAS_EXEC, "{} is over MAX_GAS_EXEC", r.label);
    }
    std::fs::write(harness::results_dir().join("stage5-vault-v5.md"), out).unwrap();
}
