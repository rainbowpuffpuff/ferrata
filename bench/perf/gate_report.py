#!/usr/bin/env python3
"""lez/results/perf-gate-sequencer.md: RFP-021 R.9, R.10 and P.6 from the gate runs on a LEZ sequencer
(bench/perf/gate-sequencer.sh), each run's tables (bench/perf/summarize_gate.py) and the runs side by side.

    python3 -I bench/perf/gate_report.py bench/perf/results/gate-g2 bench/perf/results/gate-g3 ... \
        > lez/results/perf-gate-sequencer.md
"""

import contextlib
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import summarize_gate  # noqa: E402

HEADER = """# RFP-021 R.9, R.10 and P.6 on a running LEZ sequencer: several updater daemons on one instance

Generated by `python3 -I bench/perf/gate_report.py {runs}`. **Measured** on the build box (a Modal
container), on LEZ v0.4.0-rc1's own sequencer with a Logos Blockchain node (LEZ's local configuration; nothing is
sent to any public network): each run is `bash bench/perf/gate-sequencer.sh NAME` with the parameters in its
`machine.txt`. A new zone gets this tree's attestation and bridge programs (`lez/crown/session.sh a`), then
`ferrata-updater` daemons (the build of `lez/updater/sequencer`, each with its own payer) follow the lab's recorded
mainnet chain (`lez/lab/results/record/net/mainnet`), which `bench/perf/beacon_replay.py` reveals on loopback one
recorded update every `GATE_STEP` seconds, as a beacon node's light-client API would have served it. Every daemon
reads the chain through its follower (`wait_final = true`: blocks final on Bedrock), re-checks the instance right
before each transaction, and defers each (job, step) by `H(key, job, step) mod W` rounds; the adversary never defers
(`W` = 1) and polls twice as often. Each daemon runs under GNU time, is sampled every 5 s, and reaches the sequencer
and its beacon API through its own byte-counting proxy. A transaction is *applied*, *refused* (included, its
program refused it: charged) or *rejected* (dropped: nothing charged).

"""


def main():
    runs = sys.argv[1:]
    print(HEADER.format(runs=" ".join(runs)))
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        keys = [summarize_gate.summarize(r) for r in runs]
        if len(keys) > 1:
            sys.argv = [sys.argv[0]]  # main() prints only the side-by-side table from keys below
    print(out.getvalue())
    if len(keys) > 1:
        print("## The runs side by side\n")
        print("| run | honest daemons' deferral window (rounds of s) | adversary | jobs | steps applied twice | latency median / p90 (s) | finished by | gas multiple (all daemons) | honest refused / applied (A3's gate: at most 0.10) | honest-1's share of the honest fees (A3's gate: 0.35–0.65) |")
        print("|---|---|---|---:|---:|---|---|---:|---:|---:|")
        fmt = lambda v, f: f.format(v) if v is not None else "—"
        for k in keys:
            print(f"| {k['run']} | {k.get('window', '?')} of {k.get('poll', '?')} | {'yes' if k.get('adversary') else 'no'} | "
                  f"{k.get('jobs', 0)} | {k.get('twice', 0)} | {fmt(k.get('lat_med'), '{:.0f}')} / {fmt(k.get('lat_p90'), '{:.0f}')} | "
                  f"{', '.join(f'{a} {b}' for a, b in sorted(k.get('who', {}).items()))} | {fmt(k.get('mult'), '{:.3f}')} | "
                  f"{fmt(k.get('r9'), '{:.4f}')} | {fmt(k.get('share'), '{:.3f}')} |")


if __name__ == "__main__":
    main()
