#!/usr/bin/env python3
"""RFP-021 P.3: the tracking cost of an instance, per update, per day and per period, measured over the lab's eight
days on a running LEZ v0.4.0-rc1 sequencer (lez/lab/results/record: every transaction the lab sent, with the gas and
the fee its sequencer charged, read back through LEZ's chain_state), and amortised per attestation, apart from the
verification cost of each attestation. Usage:
  python3 -I bench/perf/tracking_cost.py lez/lab/results/record > lez/results/perf-tracking.md"""

import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

# A statement's own verification, one transaction each (lez/results/perf-state.md, section 2, this tree's program).
VERIFY = [("event log (receipt of 7 logs)", 93_316, 2_519), ("storage slot", 275_865, 7_338),
          ("account", 166_249, 4_356), ("one EIP-2935 hop, then a slot", 499_277, 13_578)]
STEP = re.compile(r"^(mainnet|sepolia) #(\d+) (finality|period|init)\b.*? (Open \(step 1\)|Miller \(step 2\)|Finish \(step 3\)|adopt \d/\d|Init|.*)$")


def g(n):
    return f"{int(round(n)):,}"


def main():
    rec = Path(sys.argv[1])
    rows = [l.split("\t") for l in (rec / "run.tsv").read_text().splitlines()]
    head, rows = rows[0], rows[1:]
    c = {h: i for i, h in enumerate(head)}
    jobs = defaultdict(lambda: dict(tx=0, exec=0, stor=0, fee=0, refused=0))
    for r in rows:
        m = STEP.match(r[c["step"]])
        if not m or r[c["phase"]].startswith("deploy"):
            continue
        chain, seq, kind = m.group(1), int(m.group(2)), m.group(3)
        j = jobs[(chain, seq)]
        j.update(chain=chain, seq=seq, kind=kind, session=r[c["phase"]])
        if r[c["status"]] != "applied":
            j["refused"] += 1
        j["tx"] += 1
        j["exec"] += int(r[c["exec_gas"]] or 0)
        j["stor"] += int(r[c["stor_gas"]] or 0)
        j["fee"] += int(r[c["fee"]] or 0)
    sessions = sorted({j["session"] for j in jobs.values()})

    def hours(s):
        return int(s[6:8]) * 24 + int(s[9:11]) + int(s[11:13]) / 60

    days = (hours(sessions[-1]) - hours(sessions[0])) / 24
    # Steady state: after the first session, which deployed the program and caught each instance up from its
    # bootstrap (Sepolia: 33 period updates through the Gloas fork). The days counted are those between the first
    # session and the last, each later session's jobs being the two hours before it.
    steady = [j for j in jobs.values() if j["session"] != sessions[0] and j["kind"] != "init"]
    print("# RFP-021 P.3: tracking cost per update, per day and per period, and amortised per attestation\n")
    print("Generated by `python3 -I bench/perf/tracking_cost.py lez/lab/results/record`. **Measured**: every transaction the")
    print("lab sent to its LEZ v0.4.0-rc1 sequencer (one validator, Logos Blockchain node) while it followed mainnet and Sepolia")
    print(f"from {sessions[0]} to {sessions[-1]} ({len(sessions)} sessions, {days:.1f} days; one session every two hours), with")
    print("the execution gas, storage gas and fee its sequencer charged (`run.tsv`, read back from the chain: lez/lab/README.md).")
    print("Fees are in LEZ's native unit at the base fees the lab's chain had (8 per unit of each gas). The public job path")
    print("(three transactions an update, five at a handoff: lez/results/stage1-*.md). The lab's program is an earlier image")
    print("than this tree's (lez/lab/README.md); this tree's per-step gas is within 0.3% of it (`lez/results/perf-state.md` §3).\n")

    print("## Per update (each job of the record)\n")
    print("| chain | kind | jobs | transactions each | exec gas per job (median) | storage gas per job | fee per job (median) | refused |")
    print("|---|---|---:|---:|---:|---:|---:|---:|")
    per = defaultdict(list)
    for j in jobs.values():
        per[(j["chain"], j["kind"])].append(j)
    for (chain, kind), js in sorted(per.items()):
        print(f"| {chain} | {kind} | {len(js)} | {statistics.median(j['tx'] for j in js):.0f} | {g(statistics.median(j['exec'] for j in js))} | "
              f"{g(statistics.median(j['stor'] for j in js))} | {g(statistics.median(j['fee'] for j in js))} | {sum(j['refused'] for j in js)} |")

    print("\n## Per day and per period, as the lab ran (one finality update every two hours, each period's update when served)\n")
    print(f"Steady state: the {len(sessions) - 1} sessions after the first (which deployed the program and caught each instance up")
    print(f"from its bootstrap), {days:.2f} days.\n")
    print("| chain | jobs | of which period updates | exec gas | storage gas | fees | exec gas per day | fees per day | per period (27.3 h): exec gas | fees |")
    print("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    tot = {}
    for chain in ("mainnet", "sepolia"):
        js = [j for j in steady if j["chain"] == chain]
        e, s, f = sum(j["exec"] for j in js), sum(j["stor"] for j in js), sum(j["fee"] for j in js)
        per_day_e, per_day_f = e / days, f / days
        per_period = 256 * 32 * 12 / 86400
        tot[chain] = (per_day_e, per_day_f)
        print(f"| {chain} | {len(js)} | {sum(1 for j in js if j['kind'] == 'period')} | {g(e)} | {g(s)} | {g(f)} | {g(per_day_e)} | "
              f"{g(per_day_f)} | {g(per_day_e * per_period)} | {g(per_day_f * per_period)} |")

    print("\n## Amortised per attestation (mainnet, as the lab ran), apart from each attestation's own verification\n")
    e_day, f_day = tot["mainnet"]
    print("| attestations a day | tracking: exec gas per attestation | tracking: fee per attestation |" +
          "".join(f" verification, {w}: exec gas / fee |" for w, _, _ in VERIFY))
    print("|---:|---:|---:|" + "---:|" * len(VERIFY))
    for n in (1, 10, 100, 1_000, 10_000):
        print(f"| {g(n)} | {g(e_day / n)} | {g(f_day / n)} |" + "".join(f" {g(ve)} / {g(8 * (ve + vs))} |" for _, ve, vs in VERIFY))
    print("\nThe tracking columns divide the measured daily cost by the number of attestations that use the instance's records;")
    print("the verification columns are each attestation's own transaction (fee at base fee 8 on both gases), paid by its")
    print("consumer whatever the number. An instance's tracking is shared by every consumer of every program that reads its records.")


if __name__ == "__main__":
    main()
