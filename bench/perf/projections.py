#!/usr/bin/env python3
"""RFP-021 P.7 and RFP-022 P.7: the state-growth projections, computed from measured inputs only: each account's size
in LEZ's serialized state and its growth per record (lez/results/perf-state.md, bench/perf/state.sh), the records the
lab wrote per day in operation (lez/results/perf-tracking.md), and the vault slots each Ethereum operation creates
(lez/results/perf-state-ethereum.txt, vault/test/StateGrowth.t.sol). The projections are *derived*: a measured size
times a count.

    python3 -I bench/perf/projections.py      # from the repository root
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
YEAR_DAYS = 365.25
PERIOD_H = 8192 * 12 / 3600  # a sync-committee period, 27.3 h


def num(s):
    return float(s.replace(",", ""))


def mb(b):
    return f"{b / 1e6:,.2f} MB" if b < 1e9 else f"{b / 1e9:,.2f} GB"


def main():
    state = (ROOT / "lez/results/perf-state.md").read_text()
    tracking = (ROOT / "lez/results/perf-tracking.md").read_text()
    eth = (ROOT / "lez/results/perf-state-ethereum.txt").read_text()

    # Attestation program: a record's size with its key, and the growth measured from 0 to 100,000 records.
    rec = re.search(r"^\| header\(id, slot\) record \| (\d+) \| (\d+) \| (\d+) \|", state, re.M)
    rec_b = num(rec.group(3))
    sec2 = state.split("## 2.")[1].split("## 3.")[0]
    grow = [(int(num(m.group(1))), int(num(m.group(2)))) for m in
            re.finditer(r"^\| ([\d,]+) \| ([\d,]+) \| [\d.]+ \| [\d,]+ \|", sec2, re.M)]
    per_rec = (grow[-1][1] - grow[0][1]) / (grow[-1][0] - grow[0][0])
    # The lab's records: one per applied finality update; jobs per day in steady state.
    lab = re.search(r"^\| mainnet \| (\d+) \| (\d+) \| [\d,]+ \| [\d,]+ \| [\d,]+ \| ([\d,]+) \|", tracking, re.M)
    jobs, periods = int(lab.group(1)), int(lab.group(2))
    days = float(re.search(r"Steady state: the 97 sessions after the first .*?, ([\d.]+) days", tracking, re.S).group(1))
    per_day = jobs / days  # each applied job writes one header record (a finality update or a handoff)

    print("# State-growth projections (RFP-021 P.7, RFP-022 P.7)\n")
    print("Generated by `python3 -I bench/perf/projections.py` from measured inputs only: account sizes and growth per")
    print("record in LEZ v0.4.0-rc1's serialized state ([`perf-state.md`](perf-state.md)), the records the lab wrote in")
    print("operation ([`perf-tracking.md`](perf-tracking.md)), the vault slots each Ethereum operation creates")
    print("([`perf-state-ethereum.txt`](perf-state-ethereum.txt)). Each projection is *derived*: a measured size times a")
    print("count. LEZ v0.4 charges storage gas on a transaction's bytes, not on the state it leaves: the growth is disk on")
    print("every node, not a fee.\n")
    print("## RFP-021 P.7: record state per instance, one and five years\n")
    print(f"A record is **{rec_b:,.0f} B** in the serialized state (its 32-byte key and its `Account`); measured growth "
          f"{per_rec:,.2f} B per record from {grow[0][0]:,} to {grow[-1][0]:,} records. The instance (593 B) is constant; a "
          f"job's account (1,110 B) is cleared by `Finish`.\n")
    print("| cadence | records a year | one year | five years | basis of the count |")
    print("|---|---:|---:|---:|---|")
    rows = [
        ("as the lab ran (one update every two hours, each period's)", per_day * YEAR_DAYS,
         f"measured: {jobs} jobs in {days} days on mainnet ({periods} of them period updates)"),
        ("the design's: one an hour while roots are imported, plus each period's", 24 * YEAR_DAYS + YEAR_DAYS * 24 / PERIOD_H,
         "8,766 hourly updates and 321 period updates a year"),
        ("every finalized epoch (6.4 min), as the live Sepolia daemon ran", YEAR_DAYS * 86400 / 384, "an update per epoch"),
    ]
    for name, n, basis in rows:
        print(f"| {name} | {n:,.0f} | {mb(n * per_rec)} | {mb(5 * n * per_rec)} | {basis} |")
    # Jobs that never finish: abandoned jobs come on top of the completed ones, at most one per extra racing operator
    # per update (each operator opens at most one job per update).
    job_b = num(re.search(r"^\| job\(id, job_id\)[^|]*\| \d+ \| \d+ \| (\d+) \|", state, re.M).group(1))
    design = rows[1][1]
    print(f"\nA job that never finishes leaves its account ({job_b:,.0f} B; clean-up is not built). With k operators racing "
          f"at the design's cadence, at most one abandoned job per extra operator per update ({design:,.0f} a year): "
          f"(k − 1) × {mb(design * job_b)} a year and (k − 1) × {mb(5 * design * job_b)} in five years; none with one "
          f"operator.")

    # Bridge program.
    nul = re.search(r"^\| ([\d,]+) \| ([\d,]+) \| ([\d.]+) \| ([\d,]+) \| ([\d.]+) \|", state.split("nullifier copies")[1], re.M)
    nul_b, burn_b = num(nul.group(3)), num(nul.group(5))
    root = re.search(r"root\(cid, \d+\) \| (\d+) \| (\d+) \|", state)
    root_b = num(root.group(2)) + 32
    slots = {m.group(1): (int(m.group(2)), int(m.group(3))) for m in
             re.finditer(r"GROWTH\t(.*?)\tops.*\n\s+(\d+) (\d+) \d+", eth)}
    rel_ops, rel_slots = slots["releases, 25 more (total)"]
    dep_new_ops, dep_new_slots = slots["deposits by 25 new addresses (total)"]
    dep_rep_ops, dep_rep_slots = slots["deposits by the same 25 addresses again (total)"]
    one_new = slots["deposit, another address's first"][1]
    print("\n## RFP-022 P.7: bridge state at 1M and 10M operations\n")
    print(f"Measured per record: a nullifier {nul_b:,.0f} B, a burn record {burn_b:,.0f} B (LEZ's serialized state, key "
          f"included); Ethereum: a release creates {rel_slots / rel_ops:g} vault slot ({rel_slots} for {rel_ops}), a new "
          f"depositor's first deposit {one_new} ({dep_new_slots} for {dep_new_ops} new depositors: one each and "
          f"{dep_new_slots - dep_new_ops} as the deposit tree's frontier took new levels; the frontier is 32 slots at "
          f"most, ever), a repeat deposit none ({dep_rep_slots} for {dep_rep_ops}: a frontier level).\n")
    print("| operations | LEZ: nullifier records (claims) | LEZ: burn records (burns) | Ethereum: vault slots for releases | Ethereum: vault slots for deposits, every depositor new / all repeat |")
    print("|---:|---:|---:|---:|---|")
    for n in (1_000_000, 10_000_000):
        print(f"| {n:,} | {mb(n * nul_b)} | {mb(n * burn_b)} | {n * rel_slots / rel_ops:,.0f} ({mb(n * rel_slots / rel_ops * 64)} of keys and values) | "
              f"{n * one_new:,} + at most 32 / at most 32 |")
    print(f"\nRoots grow with the import cadence, not with deposits: {root_b:,.0f} B each (173 B `Account` and its key), "
          f"8,766 a year at one an hour: {mb(8766 * root_b)} a year. Ethereum slot bytes are counted as a 32-byte key and a "
          f"32-byte value (the trie's own overhead is the client's).")


if __name__ == "__main__":
    main()
