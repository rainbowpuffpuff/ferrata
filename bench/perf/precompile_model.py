#!/usr/bin/env python3
"""RFP-021 P.8: the cycle-count delta between the in-program BLS12-381 path and a hypothetical native precompile,
modelled from measured inputs. Usage (from the repository root):
  python3 -I bench/perf/precompile_model.py bench/perf/results > lez/results/perf-precompile.md

Inputs, all measured: the program's per-step cycles (bench/perf/results/dump-index.tsv: this tree's program, the
executions LEZ meters, lez/harness/src/bin/perf_prove.rs --dump); the BLS share of `Open` (bench/RESULTS.md, the bare
guest with the same RISC Zero-accelerated blst: hash-to-G2 and the subtractive aggregation); the native time of the
same operations (bench/precompile, blst 0.3.16 on the build box's CPU, one thread, median of 300) and the executor's
throughput on the same CPU (perf_prove --exec: user cycles per second of each step, median of 5)."""

import sys
from pathlib import Path

# bench/RESULTS.md, "PHASES: update_1 against the post-update_0 store" (blst-accel, the bare guest): the BLS work
# inside the program's `Open` handler.
OPEN_BLS = [("hash-to-G2 of the signing root, to affine", 1_169_105, "hash_to_g2"),
            ("signing key: aggregate minus 2 non-signers, negated", 285_875, "aggregate_subtract_2")]
# The same table: final exponentiation and the check against one (the rest of the Finish handler is bookkeeping).
FINAL_EXP = 3_581_111
# EIP-2537 (Ethereum's BLS12-381 precompiles, in Pectra): gas of the same operations, as a reference point.
EIP2537 = {"hash_to_g2": ("MAP_FP2_TO_G2 (the field-to-curve map only; hashing to the field is extra)", 23_800),
           "aggregate_subtract_2": ("2 G1ADD (and decompression, not priced: EIP-2537 takes uncompressed points)", 2 * 375),
           "miller_loops_2_and_mul": ("PAIRING_CHECK, k = 2: 32,600 k + 37,700 (Miller loops and final exponentiation)", 102_900),
           "final_exp_and_is_one": ("(inside PAIRING_CHECK above)", 0),
           "adopt_256_uncompressed": ("255 G1ADD (the sum; recompression not priced)", 255 * 375)}


def g(n):
    return f"{int(round(n)):,}"


def main():
    d = Path(sys.argv[1])
    native = {}
    for line in (d / "precompile-native.tsv").read_text().splitlines()[1:]:
        op, ns, _ = line.split("\t")
        native[op] = float(ns)
    rate = {}
    for line in (d / "executor-rate.tsv").read_text().splitlines():
        f = line.split("\t")
        if f[0] == "EXEC":
            rate[f[2]] = (int(f[3]), float(f[4]), float(f[5]))  # handler -> cycles, seconds, Mcycles/s
    idx = [l.split("\t") for l in (d / "dump-index.tsv").read_text().splitlines()]
    c = {h: i for i, h in enumerate(idx[0])}
    steps = {}
    for r in idx[1:]:
        steps.setdefault((r[c["action"]], r[c["handler"]]), int(r[c["exec_cycles"]]))
    fin = {h: steps[(a, h)] for (a, h) in steps if a.startswith("finality update")}
    handoff = {h: steps[(a, h)] for (a, h) in steps if a.startswith("committee handoff")}
    update_total = sum(int(r[c["exec_cycles"]]) for r in idx[1:] if r[c["action"]].startswith("finality update"))
    handoff_total = sum(int(r[c["exec_cycles"]]) for r in idx[1:] if r[c["action"]].startswith("committee handoff"))

    def charge(op, handler):
        return native[op] * 1e-9 * rate[handler][2] * 1e6

    rows = [  # step, BLS operation, in-program cycles of it, native op, the handler whose executor rate applies
        ("Open", OPEN_BLS[0][0], OPEN_BLS[0][1], OPEN_BLS[0][2], "Open"),
        ("Open", OPEN_BLS[1][0], OPEN_BLS[1][1], OPEN_BLS[1][2], "Open"),
        ("Miller", "two Miller loops and their product (the whole step)", fin["Miller"], "miller_loops_2_and_mul", "Miller"),
        ("Finish", "final exponentiation and the check against one", FINAL_EXP, "final_exp_and_is_one", "Finish"),
    ]
    print("# RFP-021 P.8: in-program BLS12-381 against a hypothetical native precompile, modelled\n")
    print("Generated by `python3 -I bench/perf/precompile_model.py bench/perf/results` from measured inputs (each named below);")
    print("the model is the only thing not measured. **A precompile is reachable only from public transactions**: a LEZ")
    print("node would run it natively when it executes a public transaction; a private transaction's program runs inside")
    print("the zkVM proof, where only RISC Zero's own accelerators exist (the program already uses RISC Zero's accelerated")
    print("blst, `v0.3.16-risczero.0`). So the proven path (`VerifyAll` in a private actor) would not gain from it.\n")
    print("**The model.** LEZ charges a public transaction's execution gas as the user cycles the executor meters. A native")
    print("precompile would be priced by the work it costs a node; the model prices it at time parity: the native time of")
    print("the operation multiplied by the executor's own throughput on the same CPU, so that a node spends the same wall")
    print("time per unit of gas inside and outside the zkVM. (A chain would add a safety margin; at ten times the native")
    print("cost the conclusions below do not change.) Native times: blst 0.3.16, one thread, the build box's CPU, median")
    print("of 300 (`bench/precompile`). Executor throughput: the same step executed five times by RISC Zero's executor")
    print("(`perf_prove --exec`), median.\n")
    print("## Executor throughput, measured (this tree's program)\n")
    print("| step | user cycles | wall time (s) | Mcycles/s |\n|---|---:|---:|---:|")
    for h, (cy, s, mhz) in rate.items():
        print(f"| {h} | {g(cy)} | {s:.4f} | {mhz:.2f} |")
    print("\n## Native time of each BLS operation, measured\n")
    print("| operation | median µs |\n|---|---:|")
    for op, ns in native.items():
        print(f"| `{op}` | {ns / 1000:.1f} |")
    print("\n## The delta per step of a finality update (mainnet update_1, 510 of 512 signers)\n")
    print("| step | BLS operation | in-program cycles | native µs | precompile, modelled (cycles) | delta (cycles) | EIP-2537 reference (gas) |")
    print("|---|---|---:|---:|---:|---:|---|")
    tot_in = tot_pc = 0
    for step, what, cyc, op, h in rows:
        pc = charge(op, h)
        tot_in += cyc
        tot_pc += pc
        ref, gas = EIP2537[op]
        print(f"| {step} | {what} | {g(cyc)} | {native[op] / 1000:.1f} | {g(pc)} | {g(cyc - pc)} | {g(gas)}: {ref} |")
    rest = update_total - tot_in
    print(f"| **update** | BLS in all | **{g(tot_in)}** | | **{g(tot_pc)}** | **{g(tot_in - tot_pc)}** | |")
    print(f"\nThe finality update's three transactions meter **{g(update_total)}** cycles in all (dump-index.tsv); with the")
    print(f"BLS work as a precompile priced at time parity they would meter **{g(rest + tot_pc)}**, {update_total / (rest + tot_pc):.1f}x less:")
    print(f"the non-BLS work ({g(rest)}: SSZ hashing, Merkle branches, decoding, the job's state) is what remains, and the")
    print("whole update would fit one transaction (the target is 5M, the limit 10M) instead of three.")
    adopt_parts = [int(r[c["exec_cycles"]]) for r in idx[1:] if r[c["action"]].startswith("committee handoff") and r[c["handler"]] == "Adopt"]
    pc_adopt = charge("adopt_256_uncompressed", "Adopt")
    print(f"\n**A handoff** adds the next committee's adoption, two parts of 256 keys: {' and '.join(g(x) for x in adopt_parts)} cycles,")
    print(f"each modelled at {g(pc_adopt)} as a precompile (native {native['adopt_256_uncompressed'] / 1000:.1f} µs per part: deserialize,")
    print("check on the curve, recompress and compare, sum). The handoff's five transactions meter")
    h_delta = (sum(x[2] for x in rows[:2]) - charge("hash_to_g2", "Open") - charge("aggregate_subtract_2", "Open")
               + handoff["Miller"] - charge("miller_loops_2_and_mul", "Miller") + FINAL_EXP - charge("final_exp_and_is_one", "Finish")
               + sum(adopt_parts) - 2 * pc_adopt)
    print(f"{g(handoff_total)}; with the precompile about {g(handoff_total - h_delta)} (its own Miller step, {g(handoff['Miller'])}; the")
    print("BLS share of its Open taken as update_1's).")
    print(f"\nFor reference: blst's whole `fast_aggregate_verify` over 512 keys, natively, {native['fast_aggregate_verify_512'] / 1000:.0f} µs")
    print(f"(time parity at 13.8 Mcycles/s: about {g(native['fast_aggregate_verify_512'] * 1e-9 * 13.82e6)} cycles); EIP-2537's gas for")
    print("the pairing check alone, 102,900, is what Ethereum charges for the operation that costs this program 6.9M cycles.")
    print("\n**What it would change.** On the public path the tracking cost per update (RFP-021 P.3, `perf-tracking.md`) would")
    print(f"fall about {update_total / (rest + tot_pc):.0f}-fold; the proven path and every private consumer would not change. Whether a")
    print("follow-on precompile RFP is warranted turns on how many instances follow Ethereum publicly: at one update every two")
    day = 127_294_275  # mainnet, steady state, lez/results/perf-tracking.md
    print(f"hours an instance pays {g(day)} execution gas a day (measured, `perf-tracking.md`); with the precompile about")
    print(f"{g(day * (rest + tot_pc) / update_total)} (the same days, each update scaled by the ratio above; handoffs alike).")


if __name__ == "__main__":
    main()
