#!/usr/bin/env python3
"""RFP-022 P.5: deposit-to-mint and burn-to-release latency of a crown run on Sepolia (testnet parameters), from the
run's own records only: stages.done (each stage's end time and duration, written by the runner), captures/*.json (the
finalized slot each capture proved, the captured block's header), lez/session-b/logs/driver.log (every LEZ
transaction's send-to-final time and each real proof's time). Nothing is fetched.

    python3 -I bench/perf/latency_bridge.py e2e/runs/crown-live-3 > lez/results/perf-latency-bridge.md
"""

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

SEPOLIA_GENESIS = 1655733600  # beacon chain genesis time (Sepolia)
SLOT_S, EPOCH_SLOTS = 12, 32
FINALITY_EPOCHS = 2  # a checkpoint is finalized when the epoch after next is justified (Casper FFG, honest majority)


def iso(t):
    return datetime.fromtimestamp(t, timezone.utc).strftime("%H:%M:%SZ")


def unix(s):
    return datetime.strptime(s, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc).timestamp()


def mins(s):
    return f"{s / 60:.1f} min"


def main():
    run = Path(sys.argv[1])
    stages = {}
    for line in (run / "stages.done").read_text().splitlines():
        name, end, dur = line.split()
        stages[name] = (unix(end), float(dur.rstrip("s")))
    cap = {}
    for i in (1, 2):
        c = json.loads((run / f"captures/capture-{i}.json").read_text())
        b = json.loads((run / f"captures/capture-{i}/block.json").read_text())["result"]
        cap[i] = dict(block=c["block"], finalized_slot=c["finalized_slot"], block_time=int(b["timestamp"], 16))
    txs = []  # (label, send-to-final s, proof s or 0), in the driver's order
    proof = {}
    for line in (run / "lez/session-b/logs/driver.log").read_text().splitlines():
        m = re.search(r"\[crown-b\] (.*?): executed, proven and sent in ([\d.]+) s", line)
        if m:
            proof[m.group(1)] = float(m.group(2))
            continue
        m = re.search(r"\[crown-b\] (.*?)\s+applied\s+gas\s+(\d+)\s+block\s+(\d+)\s+\+\s*([\d.]+)s", line)
        if m:
            label = m.group(1).strip()
            p = next((v for k, v in proof.items() if label.startswith(k)), 0.0)
            txs.append(dict(label=label, gas=int(m.group(2)), block=int(m.group(3)), final_s=float(m.group(4)), proof_s=p))
    b_end, b_dur = stages["lez-b"]
    b_start = b_end - b_dur
    busy = sum(t["final_s"] + t["proof_s"] for t in txs)
    overhead = b_dur - busy  # the zone restored and started, the wallet synced: before the first transaction
    t = b_start + overhead
    for x in txs:
        t += x["proof_s"] + x["final_s"]
        x["at"] = t

    def first(pred):
        return next(x for x in txs if pred(x["label"]))

    claim1 = first(lambda l: l.startswith("bridge ClaimPrivately"))
    claim0 = first(lambda l: l.startswith("bridge Claim: deposit 0"))
    upd2 = [x for x in txs if x["label"].startswith("stage 2 finality update")]
    imp2 = first(lambda l: l.startswith("bridge ImportRoot n=2"))
    burn = txs[-1]

    print("# RFP-022 P.5: deposit to mint and burn to release, measured on Sepolia\n")
    print(f"Generated by `python3 -I bench/perf/latency_bridge.py {run}` from the run's own records (`stages.done`, the")
    print("captures, LEZ session B's driver log); nothing is fetched. **Measured** on the live round trip `crown-live-3`")
    print("(12 November 2026; EVIDENCE row 91, [`e2e/runs/crown-live-3/README.md`](../../e2e/runs/crown-live-3/README.md)): the final")
    print("programs, FerrataVault v5 in mode (B) on Sepolia with **testnet parameters** (W = 1 h, release delay 120 s, n = t = 1),")
    print("LEZ v0.4.0-rc1 on a devnet we ran (one validator; LEZ testnet 0.4 is not released). The runner does each stage as")
    print("soon as it can; nobody waited by hand. Times are UTC. *Derived* marks the one figure taken from a protocol constant")
    print("rather than a record: when Ethereum finalizes a checkpoint (two epochs after its slot).\n")

    d1_end, d1_dur = stages["deposit1"]
    cp_t = SEPOLIA_GENESIS + cap[2]["finalized_slot"] * SLOT_S
    fin_t = cp_t + FINALITY_EPOCHS * EPOCH_SLOTS * SLOT_S
    c2_end, _ = stages["capture2"]
    print("## Inbound: deposit 1 (private kind) to its private claim applied on LEZ\n")
    print("| moment | time | from the deposit | what |")
    print("|---|---|---:|---|")
    rows = [
        ("deposit 1 included", d1_end, f"`depositETH` (leaf 1); the stage's end, at most {d1_dur:.0f} s after the block"),
        ("its checkpoint's slot", cp_t, f"finalized slot {cap[2]['finalized_slot']:,} of the update the capture used (captured block {cap[2]['block']:,} at {iso(cap[2]['block_time'])})"),
        ("Ethereum finalizes it (*derived*)", fin_t, "two epochs after the checkpoint's slot"),
        ("captured", c2_end, "the finality update covering it served and read, the vault's slots proven under its header (6 slots)"),
        ("LEZ: the update applied", upd2[-1]["at"], "Open, Miller, Finish, each final on Bedrock"),
        ("LEZ: the root imported", imp2["at"], "`ImportRoot` n = 2"),
        ("**minted (private claim applied)**", claim1["at"], f"proven in {claim1['proof_s']:.1f} s, then sent and final in {claim1['final_s']:.1f} s"),
    ]
    for name, at, what in rows:
        print(f"| {name} | {iso(at)} | {mins(at - d1_end)} | {what} |")
    total_in = claim1["at"] - d1_end
    print(f"\nAs it ran: **{mins(total_in)}** from the deposit to the mint. Broken down as RFP-022 P.5 asks:\n")
    lez_upd = sum(x["final_s"] for x in upd2)
    print("| component | s | share | basis |")
    print("|---|---:|---:|---|")
    other_b = claim1["at"] - c2_end - lez_upd - imp2["final_s"] - claim1["proof_s"] - claim1["final_s"]
    parts = [
        ("source-chain finality wait: the deposit to Ethereum finalizing its checkpoint", fin_t - d1_end, "the run's stamps; finalization two epochs after the checkpoint (*derived*)"),
        ("the finality update served and read, the capture's proofs", c2_end - fin_t, "measured (the runner's first attempt was not yet covered and waited one update, about 6.4 min)"),
        ("LEZ: the light-client update (3 transactions)", lez_upd, "measured, each send to final on Bedrock"),
        ("LEZ: the root import", imp2["final_s"], "measured"),
        ("proof generation: the private claim", claim1["proof_s"], "measured, LEZ's wallet on the crown runner's CPU (a cloud container of 16 to 32 CPUs, not a laptop: at a laptop's shape the claim takes 1,093 s, lez/results/perf-p4-laptop.md)"),
        ("privacy-motivated delay", 0.0, "none in this run (the runner claimed at once); the client's default holds a claim 1 to 12 h after its deposit (docs/guides/user-guide.md, \"Choice\" table), which would add that much"),
        ("on-chain verification: the claim, send to final", claim1["final_s"], "measured; the claim is verified inside it (P.1)"),
        ("the runner's other work in session B", other_b, "zone start and wallet sync, deposit 0's update, import and claim, done first"),
    ]
    for name, s, basis in parts:
        print(f"| {name} | {s:.1f} | {s / total_in:.0%} | {basis} |")
    steady = (fin_t - d1_end) + (c2_end - fin_t) + lez_upd + imp2["final_s"] + claim1["proof_s"] + claim1["final_s"]
    print(f"\nWithout the runner's other work (an operator already following the chain, the deposit's root imported at once):"
          f" **{mins(steady)}**, of which Ethereum's finality and the update's availability {mins(c2_end - d1_end)}. "
          f"Deposit 0 (public kind) as it ran: included {iso(stages['deposit0'][0])}, minted {iso(claim0['at'])}, "
          f"{mins(claim0['at'] - stages['deposit0'][0])} (it waited for deposit 1's capture, which the runner did first). "
          f"With the client's default hold of 1 to 12 h after the deposit, the inbound is about {mins(total_in + 3600)} to "
          f"{mins(total_in + 12 * 3600)} (*derived*).\n")

    print("## Outbound: the private burn to its release on Ethereum\n")
    order = ["checkpoint-input", "checkpoint-exec", "checkpoint-prove", "checkpoint-wrap", "submit", "wait", "finalize", "release0"]
    what = {
        "checkpoint-input": "the zone's blocks to the checkpoint's input (the burn's block final on Bedrock)",
        "checkpoint-exec": "checkpoint_b executed (its journal equals the native one)",
        "checkpoint-prove": "proof generation: the checkpoint, one NVIDIA L40S",
        "checkpoint-wrap": "proof generation: the Groth16 wrap",
        "submit": "`submitCandidate` included (on-chain verification of the checkpoint proof)",
        "wait": "the vault's wait W = 3,600 s of block time (the runner proved the two releases first, inside it)",
        "finalize": "`finalizeAttested` included",
        "release0": "the release delay (120 s), then `release` included (the release proof verified on chain)",
    }
    print("| stage | ended | s | from the burn | what |")
    print("|---|---|---:|---:|---|")
    t_burn = b_end
    t_sent = b_end - burn["final_s"]
    t_proving = t_sent - burn["proof_s"]
    for s in order:
        end, dur = stages[s]
        print(f"| {s} | {iso(end)} | {dur:.0f} | {mins(end - t_burn)} | {what[s]} |")
    rp = stages["releases-prove"]
    total_out = stages["release0"][0] - t_proving
    print(f"\nThe burn: `{burn['label']}`, proven in {burn['proof_s']:.1f} s and final on LEZ in {burn['final_s']:.1f} s "
          f"(block {burn['block']}, the last of session B, {iso(t_burn)}). From the start of the burn's proof to the release "
          f"in an Ethereum block: **{mins(total_out)}**; from its sending {mins(stages['release0'][0] - t_sent)}; from it final "
          f"on LEZ {mins(stages['release0'][0] - t_burn)}. The user's release proof and its wrap ({rp[1]:.0f} s, ended "
          f"{iso(rp[0])}) ran during W, off the critical path. Broken down:\n")
    prove = stages["checkpoint-prove"][1] + stages["checkpoint-wrap"][1]
    verify = stages["submit"][1] + stages["finalize"][1]
    # W runs from submitCandidate's block; the runner proved the releases (stage releases-prove) inside it.
    w = stages["wait"][0] - stages["submit"][0]
    rel = stages["release0"][1]
    rest = total_out - burn["proof_s"] - burn["final_s"] - prove - verify - w - rel
    print("| component | s | share |")
    print("|---|---:|---:|")
    for name, s in [("proof generation: the private burn (the user's, LEZ's wallet on the runner's CPU)", burn["proof_s"]),
                    ("source-chain finality wait: the burn sent to final on LEZ (Bedrock; a one-validator devnet)", burn["final_s"]),
                    ("proof generation (checkpoint and wrap)", prove), ("on-chain verification (`submitCandidate`, `finalizeAttested`)", verify),
                    ("the vault's wait W (rule B; testnet value 1 h), `submitCandidate` to the wait's end", w), ("release delay and the release transaction", rel),
                    ("privacy-motivated delay (none in this run; the client's default waits for the vault's release delay)", 0.0),
                    ("the checkpoint's input and execution, the runner", rest)]:
        print(f"| {name} | {s:.0f} | {s / total_out:.0%} |")
    print("\nThe source chain here is LEZ: the burn's block was final on Bedrock before the checkpoint's input was cut "
          "(the devnet's own finality; LEZ testnet 0.4's is not measured). With production parameters the vault's wait and "
          "the release delay dominate: W is 1 h in rule (B) and 3 h 16 min to 4 h 31 min in rule (A) at the default floor, "
          "and the release delay at least 24 h outside testnets (docs/design/bridge.md §11.6, §13).")


if __name__ == "__main__":
    main()
