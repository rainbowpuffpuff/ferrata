#!/usr/bin/env python3
"""RFP-021 P.5: end-to-end attestation latency, from an Ethereum event to a statement usable on LEZ, from the records
of the live run of 12-13 November 2026 (lez/updater/results/live-sepolia: ferrata-updater, the build of
lez/updater/sequencer, following Sepolia through Lodestar's public light-client API on a running LEZ v0.4.0-rc1
sequencer and Logos Blockchain node; every update's three transactions read back final on Bedrock).

For an event in the block at slot e, the statement about it is usable once a header at slot >= e is recorded on LEZ,
that is when the first applied update with finalized slot F >= e has its Finish final, plus the consuming transaction
itself. Each update's times come from the daemon's log: the slots it names (finalized F, attested A, signature S;
slot times from Sepolia's genesis, 1655733600, 12 s a slot), the moment the daemon opened the job (it had the
update), each step's send-to-final time ("+ N s") and the Finish's final time. Every slot between two consecutive
recorded headers is taken as an event's block (the window the run covered, uniformly), so the distribution is over
blocks, not over a sample of chosen events. Usage:
  python3 -I bench/perf/latency_e2e.py lez/updater/results/live-sepolia > lez/results/perf-latency-e2e.md"""

import re
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

GENESIS = 1655733600
SLOT = 12


def unix(s):
    return datetime.strptime(s, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc).timestamp()


def slot_time(s):
    return GENESIS + SLOT * s


JOB = re.compile(r"^(\S+Z) \[[^\]]+\] job 0x([0-9a-f]+): finalized slot (\d+) root \S+ \(attested slot (\d+), signature slot (\d+)")
STEP = re.compile(r"^\[updater\] \S+ fin (\d+) (Open|Miller|Finish|Adopt \d/\d|adopt \d/\d)\s+applied\s+gas\s+\d+ block\s+\d+ \+ ([\d.]+)s")
DONE = re.compile(r"^(\S+Z) \[[^\]]+\] \S+ fin (\d+) Finish applied")


def parse(root):
    jobs, steps = {}, []
    for log in sorted(Path(root).glob("zone-*/updater-u*.log")):
        for line in log.read_text(errors="replace").splitlines():
            m = JOB.match(line)
            if m:
                t, _, f, a, s = m.groups()
                jobs.setdefault(int(f), dict(open=unix(t), F=int(f), A=int(a), S=int(s), zone=log.parent.name))
                continue
            m = STEP.match(line)
            if m:
                steps.append((int(m.group(1)), m.group(2), float(m.group(3))))
                continue
            m = DONE.match(line)
            if m and int(m.group(2)) in jobs:
                jobs[int(m.group(2))].setdefault("finish", unix(m.group(1)))
    return [j for j in sorted(jobs.values(), key=lambda j: j["F"]) if "finish" in j], steps


def pct(xs, q):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(round(q * (len(xs) - 1))))]


def main():
    root = sys.argv[1]
    jobs, steps = parse(root)
    tx = [d for _, _, d in steps]
    tx_med = statistics.median(tx)
    print("# RFP-021 P.5: end-to-end attestation latency, measured on the live run of 12-13 November 2026\n")
    print("Generated by `python3 -I bench/perf/latency_e2e.py lez/updater/results/live-sepolia` from the run's own records")
    print("(daemon logs `zone-*/updater-u*.log`). **Measured** on real Sepolia blocks, Lodestar's public light-client data and")
    print("a running LEZ v0.4.0-rc1 sequencer with a Logos Blockchain node (one validator; EVIDENCE row 99): nothing is")
    print("modelled except that an event's statement is taken as usable one transaction after the record it needs, that")
    print(f"transaction's latency being the run's own median send-to-final time of a transaction ({tx_med:.1f} s, {len(tx)} transactions).\n")

    # Per update.
    rows = []
    for j in jobs:
        rows.append(dict(F=j["F"], fin_wait=slot_time(j["S"]) - slot_time(j["F"]), avail=j["open"] - slot_time(j["S"]),
                         lez=j["finish"] - j["open"], zone=j["zone"]))
    print(f"## Per update ({len(rows)} updates applied, Finish final)\n")
    print("| component | median s | p10 s | p90 s | what |")
    print("|---|---:|---:|---:|---|")
    for key, what in [("fin_wait", "finalized header's slot to the signature slot of the update that proves it (Ethereum finality)"),
                      ("avail", "signature slot to the daemon opening the job (the beacon node serving the update, the daemon's poll)"),
                      ("lez", "job opened to its Finish final on Bedrock (Open, Miller, Finish: three transactions)")]:
        xs = [r[key] for r in rows]
        print(f"| {key} | {statistics.median(xs):.0f} | {pct(xs, 0.1):.0f} | {pct(xs, 0.9):.0f} | {what} |")
    print(f"| one transaction, send to final | {tx_med:.1f} | {pct(tx, 0.1):.1f} | {pct(tx, 0.9):.1f} | each step of the run ({len(tx)}) |")

    # Per event block: every slot after a recorded header up to the next one. "Continuous": the next header is at most
    # two epochs later and the daemon opened its job within ten minutes of the previous Finish (no outage between).
    def events_of(pairs):
        out = []
        for prev, j in pairs:
            for e in range(prev["F"] + 1, j["F"] + 1):
                out.append(dict(total=j["finish"] - slot_time(e) + tx_med, to_header=slot_time(j["F"]) - slot_time(e),
                                fin=slot_time(j["S"]) - slot_time(j["F"]), avail=j["open"] - slot_time(j["S"]),
                                lez=j["finish"] - j["open"], verify=tx_med))
        return out

    pairs = list(zip(jobs, jobs[1:]))
    cont = [(p, j) for p, j in pairs if j["F"] - p["F"] <= 64 and j["open"] - p["finish"] <= 600]
    for title, sel in [("continuous operation", cont), ("every consecutive pair, the run's outages included", pairs)]:
        events = events_of(sel)
        hours = len(events) * SLOT / 3600
        print(f"\n## Per event block, {title} ({len(events)} Sepolia slots, {hours:.1f} hours of chain, {len(sel)} updates)\n")
        print("| | median | p10 | p90 | max |")
        print("|---|---:|---:|---:|---:|")
        for key, what in [("total", "**event to statement usable on LEZ**"), ("to_header", "event to the next recorded header's slot"),
                          ("fin", "that header to its finality proof (signature slot)"), ("avail", "update availability (beacon node, poll)"),
                          ("lez", "the update applied on LEZ (three transactions)"), ("verify", "the consuming transaction (verification, P.1)")]:
            xs = [ev[key] for ev in events]
            print(f"| {what} | {statistics.median(xs) / 60:.1f} min | {pct(xs, 0.1) / 60:.1f} min | {pct(xs, 0.9) / 60:.1f} min | {max(xs) / 60:.1f} min |")
    print("\nThe components of one row do not add up across columns (each column is its own distribution); for each event they")
    print("add up exactly: event to header + finality + availability + LEZ + verification = the total.")


if __name__ == "__main__":
    main()
