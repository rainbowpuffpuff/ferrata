#!/usr/bin/env python3
"""Constants of the BLS12-381 residue-witness check, derived from the field modulus p, the group
order r and the curve seed u alone. Every number-theoretic fact the check's soundness argument and
the honest witness algorithm rely on is asserted here (and again in Rust, tests/constants.rs, with
num-bigint). Prints the Rust source of src/constants.rs on stdout.

Run: python3 -I bench/residue/gen_constants.py > bench/residue/src/constants.rs
"""
import math

U = -0xD201000000010000  # the BLS12-381 seed (negative)
P = 0x1A0111EA397FE69A4B1BA7B6434BACD764774B84F38512BF6730D2A0F6B0F6241EABFFFEB153FFFFB9FEFFFFFFFFAAAB
R = 0x73EDA753299D7D483339D80809A1D80553BDA402FFFE5BFEFFFFFFFF00000001

# The BLS12 family: p and r are the polynomials of the seed.
assert R == U**4 - U**2 + 1
assert (U - 1) ** 2 * R % 3 == 0 and P == (U - 1) ** 2 * R // 3 + U

N = P**12 - 1  # the order of the cyclic group Fp12*
assert N % R == 0
H = N // R  # the final exponent; f passes the pairing check iff f^H == 1
assert H % R != 0  # r^2 does not divide N, so gcd(H, r) = 1

LAMBDA = P - U  # p + |u|: c^LAMBDA = Frobenius(c) * c^|u|
assert LAMBDA == P + 0xD201000000010000
assert LAMBDA % R == 0  # soundness needs r | LAMBDA
POLY = (1 - U) // 3  # gnark's polyFactor
assert (1 - U) % 3 == 0 and POLY == 5044125407647214251
assert LAMBDA == 3 * POLY**2 * R

# H = 27 * POLY * F with F coprime to 3, to POLY and to LAMBDA.
assert H % (27 * POLY) == 0
F = H // (27 * POLY)
assert math.gcd(F, 3) == 1 and math.gcd(F, POLY) == 1 and math.gcd(POLY, 3) == 1
assert math.gcd(F, LAMBDA) == 1

# The scaling factor lives in the subgroup of order 27 * POLY, which lies in Fp6* (27 * POLY divides
# p^6 - 1); and every nonzero element of Fp6 is killed by H (p^6 - 1 divides H): the subfield
# condition is what makes the check sound.
assert (P**6 - 1) % (27 * POLY) == 0
assert H % (P**6 - 1) == 0

LAMBDA_INV_MOD_F = pow(LAMBDA, -1, F)
A = (-pow(27 * F, -1, POLY)) % POLY  # w_P = f^(27 F A): the inverse of f's POLY-part
B = (-pow(POLY * F, -1, 27)) % 27  # w_3 = f^(POLY F B): the inverse of f's 3-part
W_EXP = 27 * A + POLY * B  # w = (f^F)^W_EXP
# Checks of the witness algorithm's exponents, for any f with f^H = 1 (cyclic group of order H):
# f = f_F f_27 f_P (CRT). (f^F)^(27 A) = f_P^(27 F A) = f_P^-1; (f^F)^(POLY B) = f_27^(POLY F B) = f_27^-1.
assert (27 * F * A) % POLY == POLY - 1 or POLY == 1
assert (POLY * F * B) % 27 == 26
assert (LAMBDA * LAMBDA_INV_MOD_F) % F == 1


def be(n, nbytes=None):
    nbytes = nbytes or (n.bit_length() + 7) // 8
    return n.to_bytes(nbytes, "big")


def rust_bytes(name, n, doc):
    b = be(n)
    rows = ["    " + ", ".join(f"0x{x:02x}" for x in b[i : i + 16]) + "," for i in range(0, len(b), 16)]
    return f"/// {doc}\npub const {name}: [u8; {len(b)}] = [\n" + "\n".join(rows) + "\n];\n"


print("// @generated by gen_constants.py from p, r and u alone (every relation asserted there).")
print("// Do not edit by hand. Big-endian exponents.")
print()
print("/// |u| = 0xd201000000010000, the absolute value of the BLS12-381 seed u (u is negative).")
print("pub const ABS_U: u64 = 0xd201_0000_0001_0000;")
print()
print(rust_bytes("H", H, "The final exponent (p^12 - 1) / r."))
print(rust_bytes("F", F, "F = H / (27 * POLY): the part of H coprime to LAMBDA."))
print(rust_bytes("LAMBDA", LAMBDA, "LAMBDA = p - u = p + |u| = 3 * POLY^2 * r."))
print(rust_bytes("LAMBDA_INV_MOD_F", LAMBDA_INV_MOD_F, "LAMBDA^-1 mod F."))
print(rust_bytes("W_EXP", W_EXP, "w = (f^F)^W_EXP = 27 A + POLY B (A = -(27F)^-1 mod POLY, B = -(POLY F)^-1 mod 27)."))
print(f"/// POLY = (1 - u) / 3 (gnark's polyFactor).\npub const POLY: u64 = {POLY};")
print(f"/// A = -(27 F)^-1 mod POLY.\npub const A: u64 = {A};")
print(f"/// B = -(POLY F)^-1 mod 27.\npub const B: u64 = {B};")
